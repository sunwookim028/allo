#!/usr/bin/env python3
"""Generate or package the flat flow's synthesis constraints."""

from __future__ import annotations

import os
import re
import shutil
from pathlib import Path


OUTPUT = Path("outputs/constraints.tcl")
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_$]*$")


def parameter(name: str, default: str) -> str:
    return os.environ.get(name, default).strip()


def number(name: str, default: float, *, positive: bool = False) -> float:
    value = float(parameter(name, str(default)))
    if positive and value <= 0:
        raise ValueError(f"{name} must be positive, got {value}")
    if not positive and value < 0:
        raise ValueError(f"{name} must be nonnegative, got {value}")
    return value


def resolve_from_construct(value: str) -> Path:
    path = Path(value).expanduser()
    if path.is_absolute():
        return path.resolve()
    construct = Path(parameter("construct_path", "undefined")).expanduser()
    if str(construct) == "undefined":
        raise ValueError("construct_path is required for a relative constraints_file")
    return (construct.resolve().parent / path).resolve()


def validate_identifier(name: str, value: str) -> str:
    if not IDENTIFIER.fullmatch(value):
        raise ValueError(f"{name} must be a simple Verilog/Tcl identifier, got {value!r}")
    return value


def generated_constraints() -> str:
    design_name = validate_identifier("design_name", parameter("design_name", "undefined"))
    clock_port = validate_identifier("clock_port", parameter("clock_port", "clk"))
    clock_name = validate_identifier("clock_name", parameter("clock_name", "ideal_clock"))
    clock_period = number("clock_period", 1.0, positive=True)
    input_delay_fraction = number("input_delay_fraction", 0.5)
    output_delay_fraction = number("output_delay_fraction", 0.0)
    max_transition_fraction = number("max_transition_fraction", 0.25, positive=True)
    max_fanout = number("max_fanout", 20.0, positive=True)
    clock_uncertainty = number("clock_uncertainty", 0.0)

    lines = [
        "# Generated by asic-flow-utilities for the standard single-clock flat flow.",
        f"set asic_clock_port [get_ports {{{clock_port}}}]",
        "if {[sizeof_collection $asic_clock_port] != 1} {",
        f"  error \"Expected exactly one clock port named {clock_port}\"",
        "}",
        f"create_clock -name {{{clock_name}}} -period {clock_period:g} $asic_clock_port",
    ]
    if clock_uncertainty > 0:
        lines.append(f"set_clock_uncertainty {clock_uncertainty:g} [get_clocks {{{clock_name}}}]")
    lines.extend([
        "set asic_nonclock_inputs [remove_from_collection [all_inputs] $asic_clock_port]",
        "if {[sizeof_collection $asic_nonclock_inputs] > 0} {",
        f"  set_input_delay -clock [get_clocks {{{clock_name}}}] "
        f"[expr {clock_period:g} * {input_delay_fraction:g}] $asic_nonclock_inputs",
        "  set_driving_cell -no_design_rule -lib_cell $ADK_DRIVING_CELL $asic_nonclock_inputs",
        "}",
        "if {[sizeof_collection [all_outputs]] > 0} {",
        f"  set_output_delay -clock [get_clocks {{{clock_name}}}] "
        f"[expr {clock_period:g} * {output_delay_fraction:g}] [all_outputs]",
        "  set_load -pin_load $ADK_TYPICAL_ON_CHIP_LOAD [all_outputs]",
        "}",
        f"set_max_fanout {max_fanout:g} [get_designs {{{design_name}}}]",
        f"set_max_transition [expr {clock_period:g} * {max_transition_fraction:g}] "
        f"[get_designs {{{design_name}}}]",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    override = parameter("constraints_file", "")
    if override:
        source = resolve_from_construct(override)
        if not source.is_file() or source.stat().st_size == 0:
            raise FileNotFoundError(f"constraints_file is missing or empty: {source}")
        text = source.read_text(errors="replace")
        if "create_clock" not in text:
            raise ValueError(f"constraints_file does not define a clock: {source}")
        shutil.copy2(source, OUTPUT)
        print(f"Packaged constraint override: {source}")
        return

    OUTPUT.write_text(generated_constraints())
    print(
        "Generated standard flat constraints for "
        f"{parameter('design_name', 'undefined')} on {parameter('clock_port', 'clk')}"
    )


if __name__ == "__main__":
    main()
