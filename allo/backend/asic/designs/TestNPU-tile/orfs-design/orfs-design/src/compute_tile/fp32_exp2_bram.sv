    rom[1020] = 23'h7F64EB;
    rom[1021] = 23'h7F9131;
    rom[1022] = 23'h7FBD7E;
    rom[1023] = 23'h7FE9D3;
  end

  // ── FP32 field extraction ────────────────────────────────────────────────
  logic        xs;
  logic [ 7:0] xe;
  logic [22:0] xm;
  assign xs = x[31];
  assign xe = x[30:23];
  assign xm = x[22:0];

  logic x_nan, x_pinf, x_ninf, x_zero;
  assign x_nan  = (&xe) & (|xm);
  assign x_pinf = (&xe) & ~(|xm) & ~xs;
  assign x_ninf = (&xe) & ~(|xm) & xs;
  assign x_zero = (xe == 8'h00);

  logic signed [8:0] xE;
  assign xE = {1'b0, xe} - 9'sd127;

  logic ovf, unf;
  assign ovf = !xs & !x_nan & (xE >= 9'sd7);
  assign unf = (xs & !x_nan & (xE >= 9'sd7)) | x_ninf;

  // ── Integer part n = floor(x) ─────────────────────────────────────────────
  logic [4:0] frac_shift;
  always_comb begin
    if (xE < 9'sd0) frac_shift = 5'd0;
    else if (xE >= 9'sd23) frac_shift = 5'd23;
    else frac_shift = xE[4:0] + 5'd1;
  end
  logic [23:0] full_mant;
  assign full_mant = {1'b1, xm};
  /* verilator lint_off UNUSEDSIGNAL */
  logic [23:0] shifted_fm;
  /* verilator lint_on UNUSEDSIGNAL */
  assign shifted_fm = full_mant << frac_shift;
  logic [22:0] frac_mant;
  assign frac_mant = shifted_fm[22:0];
  logic has_frac;
  assign has_frac = (|frac_mant) & !x_zero;

  logic [7:0] n_abs;
  always_comb begin
    if (x_zero || xE < 9'sd0) n_abs = 8'd0;
    else if (xE >= 9'sd7) n_abs = 8'd127;
    else n_abs = 8'(full_mant >> (5'd23 - xE[4:0]));
  end
  logic signed [8:0] n_int;
  always_comb begin
    if (x_zero) n_int = 9'sd0;
    else if (!xs) n_int = {1'b0, n_abs};
    else begin
      if (xE < 9'sd0) n_int = -9'sd1;
      else if (!has_frac) n_int = -{1'b0, n_abs};
      else n_int = -{1'b0, n_abs} - 9'sd1;
    end
  end

  // ── float(n) ──────────────────────────────────────────────────────────────
  logic        fn_sign;
  logic [ 7:0] fn_abs_v;
  logic [ 2:0] fn_msb;
  logic [ 7:0] fn_exp_v;
  logic [22:0] fn_mant_v;
  logic [31:0] float_n;

  assign fn_sign  = n_int[8];
  assign fn_abs_v = fn_sign ? 8'(-n_int) : 8'(n_int);
  always_comb begin
    casez (fn_abs_v)
      8'b1???????: fn_msb = 3'd7;
      8'b01??????: fn_msb = 3'd6;
      8'b001?????: fn_msb = 3'd5;
      8'b0001????: fn_msb = 3'd4;
      8'b00001???: fn_msb = 3'd3;
      8'b000001??: fn_msb = 3'd2;
      8'b0000001?: fn_msb = 3'd1;
      default:     fn_msb = 3'd0;
    endcase
  end
  logic [7:0] fn_mask_v;
  assign fn_mask_v = (8'h01 << fn_msb) - 8'h01;
  assign fn_mant_v = 23'(fn_abs_v & fn_mask_v) << (5'd23 - {2'b0, fn_msb});
  assign fn_exp_v  = 8'd127 + {5'd0, fn_msb};
  assign float_n   = (n_int == 9'sd0) ? 32'h0 : {fn_sign, fn_exp_v, fn_mant_v};

  // ── Fix 11+12a: pipeline registers (3-cycle latency) ────────────────────
  // Cycle 0: x → float_n, n_int, specials computed combinationally.
  // Cycle 1: _r2 regs drive u_f_sub; f_fp32_r captures u_f_sub output.
  // Cycle 2: f_fp32_r → lut_addr → BRAM captures rom_out_r.
  // Cycle 3: BRAM output + n_int_r → assembly result valid.
  // Fix 12a splits the Cycle-1 xe_r2_reg→u_f_sub→BRAM-addr path (11.7 ns)
  // into: xe_r2_reg→f_fp32_r (~8.7 ns) and f_fp32_r→BRAM-addr (~3 ns).
  logic xs_r2, x_nan_r2, x_pinf_r2, ovf_r2, unf_r2;
  logic [7:0] xe_r2;
  logic [22:0] xm_r2;
  logic signed [8:0] n_int_r2;
  logic [31:0] float_n_r2;
  always_ff @(posedge clk) begin
    xs_r2      <= xs;
    xe_r2      <= xe;
    xm_r2      <= xm;
    x_nan_r2   <= x_nan;
    x_pinf_r2  <= x_pinf;
    ovf_r2     <= ovf;
    unf_r2     <= unf;
    n_int_r2   <= n_int;
    float_n_r2 <= float_n;
  end

  // ── u_f_sub: f = x_r2 − float_n_r2 ──────────────────────────────────────
  logic [31:0] f_fp32;
  /* verilator lint_off PINMISSING */
  fp32_add #(
      .FORMAT("FP32")
  ) u_f_sub (
      .clk   (1'b0),
      .rst_n (1'b1),
      .a     ({xs_r2, xe_r2, xm_r2}),
      .b     ({~float_n_r2[31], float_n_r2[30:0]}),
      .result(f_fp32)
  );
  /* verilator lint_on PINMISSING */

  // ── Fix 12a: register f_fp32 to break xe_r2_reg→u_f_sub→BRAM-addr (11.7 ns) ──
  logic [31:0] f_fp32_r;
  logic signed [8:0] n_int_r3;
  logic [3:0] specials_r3;
  always_ff @(posedge clk) begin
    f_fp32_r    <= f_fp32;
    n_int_r3    <= n_int_r2;
    specials_r3 <= {x_nan_r2, x_pinf_r2, ovf_r2, unf_r2};
  end

  // ── BRAM Address: top 10 bits of f ∈ [0,1) ───────────────────────────────
  // f_fp32 biased-exp in [0,126]; shift = 126 − f_exp = leading zeros before '1'.
  // addr = {1, f_mant[22:0]} >> (13 + shift)  [take bits 9:0]
  logic [7:0] f_exp8;
  logic [3:0] shift_amt;
  assign f_exp8 = f_fp32_r[30:23];
  always_comb begin
    if (f_exp8 == 8'd0) shift_amt = 4'd10;  // f = 0 → addr = 0
    else if (f_exp8 >= 8'd117) shift_amt = 4'(8'd126 - f_exp8);  // 0..9
    else shift_amt = 4'd10;  // f < 2^-10 → addr ≈ 0
  end
  logic [ 9:0] lut_addr;
  logic [23:0] f_val24;
  assign f_val24 = {1'b1, f_fp32_r[22:0]};
  // Right-shift f_val24 by (13 + shift_amt), extract bits [9:0]
  // Correct derivation: k = floor(f × 1024) = floor(f_val24 × 2^{f_exp8-140})
  // = f_val24 >> (140 - f_exp8) = f_val24 >> (14 + shift_amt)
  // (shift_amt = 126 - f_exp8 ≥ 0).
  always_comb begin
    logic [23:0] shifted;
    if (shift_amt >= 4'd10) shifted = '0;
    else shifted = f_val24 >> (5'd14 + {1'b0, shift_amt});
    lut_addr = shifted[9:0];
  end

  // ── Register stage ────────────────────────────────────────────────────────
  logic [22:0] rom_out_r;
  logic signed [8:0] n_int_r;
  logic [3:0] specials_r;  // {x_nan, x_pinf, ovf, unf}

  always_ff @(posedge clk) begin
    rom_out_r  <= rom[lut_addr];
    n_int_r    <= n_int_r3;
    specials_r <= specials_r3;
  end

  // ── Assembly ──────────────────────────────────────────────────────────────
  always_comb begin
    if (specials_r[3]) result = {1'b0, 8'hFF, 1'b1, 22'h0};  // NaN
    else if (specials_r[2]) result = 32'h7F800000;  // +Inf
    else if (specials_r[1]) result = 32'h7F800000;  // overflow
    else if (specials_r[0]) result = 32'h00000000;  // underflow
    else result = {1'b0, 8'(n_int_r + 9'sd127), rom_out_r};
  end

endmodule
