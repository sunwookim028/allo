def make_llm(tool: AlloSpecTool) -> IsaOpenCodeLLM:
    provider, _, model_id = MODEL.partition("/")
    if TEST_BASE_URL:
        additional = [AdditionalModelProvider(
            id=provider, models=[model_id], base_url=TEST_BASE_URL,
            api_key="unused")]
    else:
        additional = [vertex_provider(provider, model_id)]
    return IsaOpenCodeLLM(
        model=MODEL,
        system_message=SYSTEM_MESSAGE,
        timeout_seconds=2400,
        # CHIA's default of 3 silently re-runs a whole prompt after a timeout;
        # in the smoke run that retry began on a blocked tool server and paid
        # for a session that could see no tools. One attempt, and the loop
        # decides what happens next.
        retries=1,
        additional_providers=additional,
        # opencode's own file and shell tools are denied: the MCP tools are the
        # agent's only capability, so it has no path to a frozen file.
        config={"*": "deny", f"{tool.name}_*": "allow"},
    )


def vertex_provider(provider: str, model_id: str) -> AdditionalModelProvider:
    if not PROJECT:
        raise RuntimeError("Set GOOGLE_CLOUD_PROJECT before running the Vertex AI agent.")
    if provider != "google-vertex" or not model_id:
        raise ValueError("TINYTPU_OPENCODE_MODEL must be google-vertex/<model-id>.")
    return AdditionalModelProvider(
        id="google-vertex",
        npm="@ai-sdk/google-vertex",
        name="Google Vertex AI",
        models=[model_id],
        options={"project": PROJECT, "location": LOCATION},
    )


RATE_LIMIT_RETRIES = 6
RATE_LIMIT_BACKOFF = 45.0


class BudgetExhausted(Exception):
    pass


class Budget:
    """Global spend cap across every worker, read from opencode's DB."""

    def __init__(self, cap_usd: float, t0_ms: int):
        self.cap, self.t0 = cap_usd, t0_ms
        self.largest_call = DEFAULT_CALL_USD

    def spent(self) -> float:
        return spent_since(self.t0)["usd"]

    def check(self, what: str):
        spent = self.spent()
        if spent + self.largest_call > self.cap:
            raise BudgetExhausted(
                f"not starting {what}: spent ${spent:.2f} + next call "
                f"~${self.largest_call:.2f} would pass the ${self.cap:.2f} cap")
        return spent

    def observe(self, usd: float):
        self.largest_call = max(self.largest_call, usd)


def ask(llm, tool, prompt, budget: Budget, what: str, calls: list):
    for attempt in range(RATE_LIMIT_RETRIES + 1):
        before = budget.check(what)
        started = time.time()
        try:
            response = get(
                llm.prompt.options(resources={"opencode_creds": 1}).chia_remote(
                    llm, prompt, [tool]))
        except RateLimitError:
            if attempt == RATE_LIMIT_RETRIES:
                raise
            delay = RATE_LIMIT_BACKOFF * (2**attempt) * (0.5 + random.random())
            print(f"  rate limited; retrying in {delay:.0f}s", flush=True)
            time.sleep(delay)
            continue
        usage = dict(getattr(response, "usage", None) or {})
        # Project from the GLOBAL spend over this call, not from `usage`: a call
        # that timed out reports no usage at all but was billed. The delta also
        # includes other workers' spend in the window -- conservative, which
        # is the right direction for a cap.
        delta = budget.spent() - before
        budget.observe(max(usage.get("cost_usd", 0.0), delta))
        calls.append({"what": what, "seconds": round(time.time() - started, 1),
                      "session_id": getattr(response, "session_id", None),
                      "global_usd_during_call": round(delta, 4),
                      "completed": bool(getattr(response, "success", True)),
                      **usage})
        print(f"  [{what}] ${usage.get('cost_usd', 0):.2f}, "
              f"{usage.get('num_turns', '?')} turns, {time.time() - started:.0f}s; "
              f"run total ${budget.spent():.2f}", flush=True)
        return response
    raise RuntimeError("unreachable")


def summarize(v: dict) -> str:
    if not v.get("ok"):
        return f"FAILED at {v.get('stage')}"
    per = ", ".join(f"{s}={c}" for s, c in v["cycles"].items())
    syn = v.get("synth", {})
    area = syn.get("area", {})
    return (f"cosim total={v['total_cycles']} [{per}] est_clock="
            f"{syn.get('estimated_ns')}ns LUT={area.get('lut')} FF={area.get('ff')} "
            f"DSP={area.get('dsp')} BRAM18K={area.get('bram_18k')}")


def _record(log_path: Path, entry: dict) -> None:
    with log_path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(entry, sort_keys=True) + "\n")


def frozen_is_clean() -> str | None:
    p = subprocess.run(["git", "status", "--porcelain", "--", *FROZEN_PATHS],
                       cwd=REPO_ROOT, capture_output=True, text=True)
    dirty = [l for l in p.stdout.splitlines() if l.strip()]
    return "\n".join(dirty) or None


def seed_spec(spec_dir: Path) -> None:
    """A private copy of the two editable files, from git HEAD."""
    spec_dir.mkdir(parents=True, exist_ok=True)
    for name in EDITABLE:
        if not (spec_dir / name).exists():
            blob = subprocess.run(
                ["git", "show", f"HEAD:examples/accelerator/tinytpu_vitis/{name}"],
                cwd=REPO_ROOT, capture_output=True, check=True).stdout
            (spec_dir / name).write_bytes(blob)


def run(task, iterations, max_debug_attempts, log_dir: Path, spec_dir: Path,
        work_dir: Path, tool_name, budget: Budget) -> int:
    dirty = frozen_is_clean()
    if dirty:
        print(f"Refusing to search: frozen files differ from HEAD:\n{dirty}")
        return 2
    runtime_env = {"working_dir": str(AGENT_DIR)}
    try:
        ray.init(address="auto", runtime_env=runtime_env)
    except ConnectionError:
        ray.init(resources={"opencode_creds": 1}, runtime_env=runtime_env)

    log_dir.mkdir(parents=True, exist_ok=True)
    log_path = log_dir / "variants.jsonl"
    calls: list[dict] = []
    seed_spec(spec_dir)
    tool = AlloSpecTool(tool_name, str(spec_dir), str(work_dir), str(AGENT_DIR),
                        str(REPO_ROOT), ALLO_PYTHON, LLVM_BUILD_DIR)
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT,
                          capture_output=True, text=True).stdout.strip()
    try:
        baseline_snapshot = tool.snapshot()
        print("=" * 72)
        print("Baseline: gate + cosim of the unmodified design")
        print("=" * 72)
        baseline = tool.evaluate(work="harness")
        print(f"  {summarize(baseline)}", flush=True)
        _record(log_path, {"iteration": 0, "kind": "baseline", "accepted": True,
                           "head": head, "verdict": baseline})
        if not baseline.get("ok"):
            print(baseline.get("detail", "")[-3000:])
            return 1

        best, best_snapshot = baseline, baseline_snapshot
        history: list[str] = []
        llm = make_llm(tool)

        for iteration in range(1, iterations + 1):
            print("=" * 72)
            print(f"Iteration {iteration}/{iterations} -- best so far "
                  f"{best['total_cycles']} cosim cycles {best['cycles']}")
            print("=" * 72, flush=True)
            tool.restore(best_snapshot)
            tried = ("\n".join(f"  - {line}" for line in history[-8:])
                     if history else "  (nothing tried yet)")
            started = time.time()
            n_calls = len(calls)
            try:
                response = ask(llm, tool, f"""TinyTPU-isa co-design task:

{task}

The spec (your two writable files) is currently the best design found so far:
cosim cycles {json.dumps(best['cycles'])} (sum {best['total_cycles']}), csynth
estimated clock {best['synth']['estimated_ns']} ns, area {json.dumps(best['synth']['area'])}.

Already attempted in this search:
{tried}

Propose ONE candidate that should lower the RTL cosim cycle count. Read the
spec first ({tool.name}_read_spec; {tool.name}_read_reference for the frozen
files and the design notes). Edit with {tool.name}_replace_text (exact text,
must occur once) -- it is far more reliable than a unified diff. Then run
{tool.name}_run_functional_check until it passes. You may run
{tool.name}_score_cycles (2-4 minutes) to see the cosim result; the harness
re-scores your final spec independently either way. Keep the change as small as
it can be while still being a real architectural change. Finish with two or
three sentences: what you changed, why it should cost fewer cycles, and whether
it relies on anything the tests happen not to exercise.
""", budget, f"iter{iteration}", calls)
            except BudgetExhausted as stop:
                print(f"  BUDGET: {stop}")
                _record(log_path, {"iteration": iteration, "kind": "stopped",
                                   "reason": str(stop)})
                break
            print(response.result, flush=True)
            summary = str(response.result)[-3000:]

            if not tool.diff_against(best_snapshot):
                # Nothing to score: the spec is the best design, already
                # measured. Re-running cosim on it would cost minutes to learn
                # a number the loop already has.
                history.append(f"iteration {iteration}: no change was made")
                print("  no change was made; nothing to score", flush=True)
                _record(log_path, {"iteration": iteration, "kind": "candidate",
                                   "diff": "", "verdict": None, "accepted": False,
                                   "reason": "no diff", "agent_summary": summary,
                                   "llm_usd": round(sum(c.get("cost_usd", 0) for c
                                                        in calls[n_calls:]), 4),
                                   "seconds": round(time.time() - started, 1),
                                   "llm_calls": calls[n_calls:]})
                continue

            verdict = tool.evaluate(work="harness")
            for attempt in range(1, max_debug_attempts + 1):
                if verdict.get("ok"):
                    break
                print(f"  candidate failed at {verdict.get('stage')} "
                      f"(debug attempt {attempt})", flush=True)
                try:
                    response = ask(llm, tool,
                                   f"The candidate failed the harness at stage "
                                   f"'{verdict.get('stage')}':\n```\n"
                                   f"{verdict.get('detail', '')[-4000:]}\n```\n"
                                   "Diagnose it, patch only microarch_isa.py and/or "
                                   "isa_dsl.py, confirm with run_functional_check, "
                                   "then stop.", budget,
                                   f"iter{iteration}-debug{attempt}", calls)
                except BudgetExhausted as stop:
                    print(f"  BUDGET: {stop}")
                    break
                print(response.result, flush=True)
                verdict = tool.evaluate(work="harness")

            elapsed = time.time() - started
            diff = tool.diff_against(best_snapshot)
            usd = round(sum(c.get("cost_usd", 0) for c in calls[n_calls:]), 4)
            entry = {"iteration": iteration, "kind": "candidate", "diff": diff,
                     "verdict": verdict, "seconds": round(elapsed, 1),
                     "agent_summary": summary, "llm_usd": usd,
                     "llm_calls": calls[n_calls:]}
            if not verdict.get("ok"):
                history.append(f"iteration {iteration}: rejected at "
                               f"{verdict.get('stage')} -- {summary[-300:]!r}")
                print(f"  REJECTED ({verdict.get('stage')}) after {elapsed:.0f}s")
                _record(log_path, {**entry, "accepted": False})
                tool.restore(best_snapshot)
                continue
            if not diff:
                history.append(f"iteration {iteration}: no change was made")
                _record(log_path, {**entry, "accepted": False, "reason": "no diff"})
                continue
            delta = verdict["total_cycles"] - best["total_cycles"]
            improved = delta < 0
            print(f"  {summarize(verdict)}")
            print(f"  {'ACCEPTED' if improved else 'REJECTED'} ({delta:+d} cosim "
                  f"cycles vs best) after {elapsed:.0f}s", flush=True)
            _record(log_path, {**entry, "accepted": improved, "delta_cycles": delta})
            history.append(f"iteration {iteration}: {'ACCEPTED' if improved else 'rejected'}"
                           f", {verdict['cycles']} ({delta:+d}) -- {summary[-300:]!r}")
            if improved:
                best, best_snapshot = verdict, tool.snapshot()
            else:
                tool.restore(best_snapshot)

        tool.restore(best_snapshot)
        print("=" * 72)
        print("Search complete")
        print(f"  baseline : {summarize(baseline)}")
        print(f"  best     : {summarize(best)}")
        print(f"  llm spend (this worker): "
              f"${sum(c.get('cost_usd', 0) for c in calls):.2f} over {len(calls)} calls")
        best_diff = tool.diff_against(baseline_snapshot)
        (log_dir / "best.diff").write_text(best_diff, encoding="utf-8")
        (log_dir / "calls.json").write_text(json.dumps(calls, indent=1))
        return 0
    finally:
        tool.stop()
        ray.shutdown()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--task", required=True)
    parser.add_argument("--iterations", type=int, default=3)
    parser.add_argument("--max-debug-attempts", type=int, default=1)
    parser.add_argument("--log-dir", type=Path, required=True)
    parser.add_argument("--spec-dir", type=Path, default=None,
                        help="this worker's private copy of the two editable files "
                             "(default: <log-dir>/spec)")
    parser.add_argument("--work-dir", type=Path, default=None,
                        help="evaluation scratch (default: .chia_scratch/<log-dir name>)")
    parser.add_argument("--tool-name", default="tinytpu")
    # No default: a run without an explicit cap does not start (preflight.py).
    parser.add_argument("--budget-usd", type=float,
                        default=os.environ.get("CHIA_BUDGET_USD"))
    parser.add_argument("--t0-ms", type=int,
                        default=int(os.environ.get("CHIA_RUN_T0_MS", "0")) or None)
    args = parser.parse_args()
    # Before any worker, tool server or model call: the right billing account,
    # the API, a per-run cap, and room under the cumulative cap.
    t0 = args.t0_ms or int(time.time() * 1000)
    preflight.require(args.budget_usd, run_t0_ms=t0)
    args.budget_usd = float(args.budget_usd)
    spec = args.spec_dir or args.log_dir / "spec"
    work = args.work_dir or REPO_ROOT / ".chia_scratch" / args.log_dir.name / "eval"
    budget = Budget(args.budget_usd, t0)
    raise SystemExit(run(args.task, args.iterations, args.max_debug_attempts,
                         args.log_dir.resolve(), spec.resolve(), work.resolve(),
                         args.tool_name, budget))


if __name__ == "__main__":
    main()
