"""Generate the impact-measurement variants of TinyTPU-isa from its PRE-LANDING
baseline.

Each variant is the baseline `microarch_isa.py` plus a small set of ASSERTED
textual patches, so the diff between a variant and the baseline is exactly the
change being priced and nothing else. The baseline is pinned to the file the
gap attribution was measured against (`BASE_COMMIT`, 252 / 919 cycles), read
from git, not the shipped file: the stack `v_design_dep_imem8` measured here is
what `main` has shipped since, with the dependence pragma now emitted by
`s.dependence` rather than patched into `kernel.cpp` (`patch_kernel` below is
how it was measured, kept as the record).

    python make_variants.py            # writes v_base.py and v_*.py here

Variants (see README.md in this directory for what each one prices):

  v_accu1   accu flattened to II=1 with the write-behind rotation of ca978b97,
            ported onto the current (widened, no-memset) design. Prices item 21.
  v_wdirect `mm` names its weights by SCRATCHPAD address and `spm` pushes the
            header + T weight words down `wcol[0]` itself. The weight `vld` is
            gone, so `vru` only handles A. Prices the B-side double handling
            through the vector-register tier.
  v_wdb     v_wdirect + a per-PE weight loader process `wld` that walks the
            weight chain and hands its PE (weight, rows) through a depth-4 FIFO,
            and a FLAT PE loop that pulls the next weight on the row that needs
            it. The FIFO is the shadow register: the next `mm`'s weight is
            latched while the current one computes (Gemmini's c1/c2).
            Prices the serial per-`mm` weight prologue.
  v_wdb_accu1  v_wdb + v_accu1.

The full list, with one line each, is the VARIANTS dict at the bottom.
"""
