def sub(src, old, new, count=1):
    n = src.count(old)
    assert n == count, f"expected {count} x {old[:70]!r}, found {n}"
    return src.replace(old, new)


def between(src, start, end, new):
    """Replace src[start:end) (end marker kept)."""
    a = src.index(start)
    b = src.index(end, a)
    return src[:a] + new + src[b:]


