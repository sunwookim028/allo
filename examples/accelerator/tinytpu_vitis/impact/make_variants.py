PATCH_KERNEL = '''

DEP_PRAGMA = os.environ.get("TPU_DEP_PRAGMA",
                            "#pragma HLS dependence variable=ar inter false")


def patch_kernel(prj):
    """Inject the dependence pragma into the emitted C++ -- the text-patch
    escape hatch cosim.py already uses for m_axi depths. Inserted as the
    first line of the first loop in accu_0 (the flat row loop)."""
    import re as _re
    path = os.path.join(prj, "kernel.cpp")
    src = open(path).read()
    a = src.index("void accu_0(")
    m = _re.compile(r"\\n(\\s*)for \\(int [^\\n]*\\{[^\\n]*\\n").search(src, a)
    assert m, "no loop in accu_0"
    ins = m.group(1) + "  " + DEP_PRAGMA + "\\n"
    if DEP_PRAGMA:
        src = src[: m.end()] + ins + src[m.end():]
    open(path, "w").write(src)
    print("  patched accu_0:", DEP_PRAGMA or "(nothing)", flush=True)
'''


def patch_accuflat(s):
    # accu's copy of a `vadd` carries 2*nr: the row counter must not depend on
    # the opcode, or the flat loop closes at II=2 on the counter (the same trap
    # spm hit in v_wdirect).
    s = sub(s, "                if op == OP_VADD:\n                    c_acc.put(rw)\n",
               "                if op == OP_VADD:\n"
               "                    wv: UInt(64) = rw\n"
               "                    wv[54:62] = nr * 2\n"
               "                    c_acc.put(wv)\n")
    s = between(s, "    @df.kernel(mapping=[1])\n    def accu():",
                "    @df.kernel(mapping=[1], args=[C])\n    def dma_st(", ACCUFLAT)
    s = sub(s, "           count(OP_MM, OP_VADD, OP_VRELU, OP_MVOUT),",
               "           rows(OP_MM, OP_VRELU, OP_MVOUT) + 2 * rows(OP_VADD),")
    return s + PATCH_KERNEL


