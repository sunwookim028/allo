ORDER = '''

_gemm_program_inorder = gemm_program


def gemm_program(M, K, N, relu=False):
    """VARIANT program order: the A `vld` moves up to just after the A
    `dma_ld` loop, ahead of the B `dma_ld`s. Same instructions, same counts,
    same RTL -- `spm` is in-order, so this lets `vru` start on A while B is
    still streaming into the scratchpad."""
    p = _gemm_program_inorder(M, K, N, relu)
    ops = [w & 0x3F for w, _ in p]
    iv = ops.index(OP_VLD)
    ie = ops.index(OP_ENDLOOP)
    assert ie < iv
    p.insert(ie + 1, p.pop(iv))
    return p
'''


def patch_order(s):
    if "def gemm_program(" not in s:
        s += BASE_PROGRAM
    return s + ORDER


# ------------------------------------------- dma_ld: no staging, strided rows
DMA_DIRECT = '''    @df.kernel(mapping=[1], args=[A, B])
    def dma_ld(lA: int8[MAXDIM * MAXDIM], lB: int8[MAXDIM * MAXDIM]):
        # VARIANT: no burst-then-rows staging. Each row is read straight from
        # m_axi at its strided address; with align_value(64) + widening the T
        # bytes are one 32-bit beat, so rows stream out from the first cycle
        # instead of after both whole-matrix bursts.
        nw: UInt(64) = c_dld.get()
        n_row: int32 = nw[0:16]
        sw: UInt(64) = c_dld.get()
        f0: int32 = 0
        f1: int32 = 0
        f2: int32 = 0
        cnt: int32 = 0
        r: int32 = -1
        for x in range(n_row):
            r += 1
            if r >= cnt:
                w0: UInt(64) = c_dld.get()
                f0 = w0[6:18]
                f1 = w0[18:30]
                f2 = w0[30:42]
                cnt = w0[54:62]
                r = 0
            pw: UInt(VW) = 0
            if f0 == 0:
                with allo.meta_for(T) as e:
                    av: int8 = lA[(f1 + r) * MAXDIM + f2 * T + e]
                    pw[8 * e : 8 * (e + 1)] = av
            else:
                with allo.meta_for(T) as e2:
                    bv: int8 = lB[(f1 + r) * MAXDIM + f2 * T + e2]
                    pw[8 * e2 : 8 * (e2 + 1)] = bv
            dma2sp.put(pw)

'''


def patch_dmadirect(s):
    return between(s, "    @df.kernel(mapping=[1], args=[A, B])\n    def dma_ld(",
                   "    @df.kernel(mapping=[1])\n    def spm():", DMA_DIRECT)


# ------------------------------------------ item (f): the `= 0` zero-fill
def patch_memset_spad(s):
    return sub(s, "        spad: UInt(VW)[SPAD_ROWS]\n", "        spad: UInt(VW)[SPAD_ROWS] = 0\n")


def patch_memset6(s):
    s = patch_memset_spad(s)
    for decl in ("        ib: UInt(64)[IMEM_SIZE]\n",
                 "        rbA: UInt(VW)[MAXDIM * WPR]\n",
                 "        rbB: UInt(VW)[MAXDIM * WPR]\n",
                 "        vr: UInt(VW)[NVR]\n",
                 "        ar: UInt(AW)[NAR]\n"):
        s = sub(s, decl, decl[:-1] + " = 0\n")
    return s


# ------------------------------------ A straight into vr (no spad, no A vld)
VRU_AD = '''    @df.kernel(mapping=[1])
    def vru():
        # VARIANT: `dma_ld` of A lands in `vr` directly (dma2vr); `vld` stays
        # for other programs; `mm` streams nr A rows to acol[0]. One vr write
        # per iteration at a muxed address and a muxed source.
        nw: UInt(64) = c_vru.get()
        n_word: int32 = nw[0:16]
        mw: UInt(64) = c_vru.get()
        vr: UInt(VW)[NVR]
        op: int32 = 0
        f0: int32 = 0
        f3: int32 = 0
        cnt: int32 = 0
        r: int32 = -1
        for x in range(n_word):
            r += 1
            if r >= cnt:
                w0: UInt(64) = c_vru.get()
                op = w0[0:6]
                f0 = w0[6:18]
                f3 = w0[42:54]
                cnt = w0[54:62]
                r = 0
            if op == OP_MM:
                vv: UInt(VW) = vr[f0 + r]
                acol[0].put(vv)
            else:
                wa: int32 = f0 + r
                if op == OP_DMA_LD:
                    wa = f3 + r
                wv: UInt(VW) = 0
                if op == OP_VLD:
                    wv = sp2vr.get()
                else:
                    wv = dma2vr.get()
                vr[wa] = wv

'''


def patch_adirect(s):
    """Apply AFTER patch_wdb/patch_wdirect."""
    s = sub(s, "    dma2sp: Stream[UInt(VW), QD]        # dma_ld -> scratchpad\n",
               "    dma2sp: Stream[UInt(VW), QD]        # dma_ld -> scratchpad\n"
               "    dma2vr: Stream[UInt(VW), QD]        # VARIANT: dma_ld -> vregs (A)\n")
    s = sub(s, "                if op == OP_DMA_LD:\n                    c_dld.put(rw)\n"
               "                    c_spm.put(rw)\n",
               "                if op == OP_DMA_LD:\n                    c_dld.put(rw)\n"
               "                    if f0 == 0:\n                        c_vru.put(rw)\n"
               "                    else:\n                        c_spm.put(rw)\n")
    s = sub(s, "            dma2sp.put(pw)\n",
               "            if f0 == 0:\n                dma2vr.put(pw)\n"
               "            else:\n                dma2sp.put(pw)\n")
    s = between(s, "    @df.kernel(mapping=[1])\n    def vru():",
                "    @df.kernel(mapping=[T, T])\n    def wld():", VRU_AD)
    s = sub(s, "           rows(OP_DMA_LD, OP_VLD) + n_mm * (T + 1),\n"
               "           rows(OP_VLD) + mm_rows,\n",
               "           sum(e[1] for e in ev if (e[0] == OP_DMA_LD and e[2] == 1)\n"
               "               or e[0] == OP_VLD) + n_mm * (T + 1),\n"
               "           sum(e[1] for e in ev if (e[0] == OP_DMA_LD and e[2] == 0)\n"
               "               or e[0] == OP_VLD) + mm_rows,\n")
    # program: A is DMA'd straight into vr, so the A vld goes
    s = sub(s, "    total_a = Kt * MAXDIM\n    assert total_a <= MAXROWS\n"
               "    ins(enc(OP_VLD, f0=A_VR, f1=A_SP, nr=total_a))\n", "")
    s = sub(s, "        enc(OP_VLD, f0=A_VR, f1=A_SP, nr=M),\n"
               "        enc(OP_MM, f0=A_VR, f1=AR_C, f2=0, f3=B_SP, nr=M),\n",
               "        enc(OP_MM, f0=A_VR, f1=AR_C, f2=0, f3=B_SP, nr=M),\n")
    return s


# ------------------------------------- imem prefetch: 8 words per iteration
def patch_imem8(s):
    """The program prefetch moves 8 instruction words per iteration into a
    cyclically partitioned `ib` (gmem0 is already 512 bits wide), so the
    56-word prefix is 7 iterations instead of 56."""
    assert "IMEM_SIZE" in s
    s = sub(s, "        for i in range(IMEM_SIZE):\n            ib[i] = l_imem[i]\n",
               "        for i in range(IMEM_SIZE // 8):\n"
               "            with allo.meta_for(8) as e8:\n"
               "                ib[8 * i + e8] = l_imem[8 * i + e8]\n")
    s = sub(s, '    s.partition(f"{top}:C", Partition.Cyclic, dim=2, factor=T)\n',
               '    s.partition(f"{top}:C", Partition.Cyclic, dim=2, factor=T)\n'
               '    s.partition("sequencer_0:ib", Partition.Cyclic, dim=1, factor=8)\n')
    return s


