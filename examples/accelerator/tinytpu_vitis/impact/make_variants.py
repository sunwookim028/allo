def patch_wdirect(s):
    s = sub(s, "        c_spm.put(ib[2])\n",
               "        c_spm.put(ib[2])\n        c_spm.put(ib[4])\n")
    # spm's copy of an `mm` carries its OWN work count (T+1) in nr and the
    # array's row count in f1, so spm's `cnt` is a plain field read. With
    # `cnt = nr; if op == OP_MM: cnt = T + 1` in spm the flat loop closed at
    # Final II = 2 (carried dependence on the row counter).
    s = sub(s, "                if op == OP_MM:\n                    c_vru.put(rw)\n",
               "                if op == OP_MM:\n"
               "                    ws: UInt(64) = rw\n"
               "                    ws[54:62] = T + 1\n"
               "                    ws[18:30] = nr\n"
               "                    c_spm.put(ws)\n"
               "                    c_vru.put(rw)\n")
    s = between(s, "    @df.kernel(mapping=[1])\n    def spm():",
                "    @df.kernel(mapping=[T, T])\n    def pe():", SPM_WD)
    s = sub(s, "           rows(OP_DMA_LD, OP_VLD),\n"
               "           rows(OP_VLD) + mm_rows + n_mm * (T + 1),\n",
               "           rows(OP_DMA_LD, OP_VLD) + n_mm * (T + 1),\n"
               "           rows(OP_VLD) + mm_rows,\n")
    # the variant's program/vadd replace the originals (defined later wins)
    s = s + PROG_WD
    return s


# ------------------------------------------ weight double-buffer: wld + flat pe
PE_WDB = '''    @df.kernel(mapping=[T, T])
    def wld():
        """VARIANT: the weight half of the old PE. Walks the header/weight chain
        exactly as `pe` used to, and hands its own PE one word per `mm` --
        (weight lane, row count) -- through `wq[i, j]`. `wq` is the shadow
        register: this process latches mm n+1's weight while the PE computes
        mm n, which is what Gemmini's c1/c2 double buffer does."""
        i, j = df.get_pid()
        nmw: UInt(VW) = 0
        with allo.meta_if(j == 0):
            nmw = wcol[i].get()
            with allo.meta_if(i != T - 1):
                wcol[i + 1].put(nmw)
        with allo.meta_else():
            nmw = wrow[i, j - 1].get()
        with allo.meta_if(j != T - 1):
            wrow[i, j].put(nmw)
        nmm: int32 = nmw[0:16]
        tq: UInt(32) = 0
        tq[0:16] = nmw[16:32]
        wq[i, j].put(tq)
        for c in range(nmm):
            hdr: UInt(VW) = 0
            with allo.meta_if(j == 0):
                hdr = wcol[i].get()
                with allo.meta_if(i != T - 1):
                    wcol[i + 1].put(hdr)
            with allo.meta_else():
                hdr = wrow[i, j - 1].get()
            with allo.meta_if(j != T - 1):
                wrow[i, j].put(hdr)
            ww: UInt(VW) = 0
            with allo.meta_if(j == 0):
                ww = wcol[i].get()
                with allo.meta_for(T - 1 - i) as _f:
                    wcol[i + 1].put(wcol[i].get())
            with allo.meta_else():
                ww = wrow[i, j - 1].get()
            with allo.meta_if(j != T - 1):
                wrow[i, j].put(ww)
            q: UInt(32) = 0
            q[0:8] = ww[8 * j : 8 * (j + 1)]
            q[8:20] = hdr[0:12]
            wq[i, j].put(q)

    @df.kernel(mapping=[T, T])
    def pe():
        """VARIANT: MAC only, one FLAT loop over every wavefront row of every
        `mm`. The next weight is taken from `wq` on the row that starts an
        `mm`; there is no prologue left in this loop."""
        i, j = df.get_pid()
        tq: UInt(32) = wq[i, j].get()
        nt: int32 = tq[0:16]
        w: int8 = 0
        cnt: int32 = 0
        r: int32 = -1
        for x in range(nt):
            r += 1
            if r >= cnt:
                q: UInt(32) = wq[i, j].get()
                w = q[0:8]
                cnt = q[8:20]
                r = 0
            a: int8 = 0
            with allo.meta_if(j == 0):
                aw: UInt(VW) = acol[i].get()
                with allo.meta_if(i != T - 1):
                    acol[i + 1].put(aw)
                a = aw[8 * i : 8 * (i + 1)]
            with allo.meta_else():
                a = a_fwd[i, j - 1].get()
            p: int32 = 0
            with allo.meta_if(i > 0):
                p = p_fwd[i - 1, j].get()
            av: int16 = a
            wv: int16 = w
            o: int32 = p + av * wv
            with allo.meta_if(i != T - 1):
                p_fwd[i, j].put(o)
            with allo.meta_else():
                cv: UInt(AW) = 0
                with allo.meta_if(j > 0):
                    cv = cw[j - 1].get()
                cv[32 * j : 32 * (j + 1)] = o
                cw[j].put(cv)
            with allo.meta_if(j != T - 1):
                a_fwd[i, j].put(a)

'''


def patch_wdb(s):
    s = patch_wdirect(s)
    s = between(s, "    @df.kernel(mapping=[T, T])\n    def pe():",
                "    @df.kernel(mapping=[1])\n    def accu():", PE_WDB)
    s = sub(s, "    cw: Stream[UInt(AW), QD][T]         # bottom row packs T psums going east\n",
               "    cw: Stream[UInt(AW), QD][T]         # bottom row packs T psums going east\n"
               "    wq: Stream[UInt(32), 4][T, T]       # VARIANT: wld -> pe, the shadow weight\n")
    return s


