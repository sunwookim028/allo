"""Emit + compile + run the EVA (eva_sb_syscredit_rtprime) chip through the Allo
SystemC backend.

Self-contained: the rtprime chip source sits alongside this script, and the
emitted SystemC project is written to ./generated/ (kernel.cpp, csim.sh, ...).

Run from this directory with the SystemC env set (see README.md):
    python build_eva_systemc.py
"""
import os, sys
os.environ.setdefault("OMP_NUM_THREADS", "8")

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)  # eva_sb_syscredit_rtprime.py is alongside this script

import eva_sb_syscredit_rtprime as e
e.M, e.N = 1, 1                 # 1x1 mesh (single PE)
e.NSTEP = 55                    # cycle budget; LANELEN follows
e.LANELEN = e.NSTEP

import allo.dataflow as df
from allo.ir.types import float16

print("allo:", df.__file__)
print(f"config: M=N=1  NSTEP=LANELEN={e.LANELEN}")

PRJ = os.path.join(HERE, "generated")
os.system(f"rm -rf {PRJ}")
# Recreate the .gitignore that `rm -rf` just deleted. Without this the transient csim
# artifacts (a ~1.5 MB csim_sim binary and the *.data vectors) come back UNIGNORED, and
# the next `git add -A` commits them -- which is exactly what happened in 72c70dc.
os.makedirs(PRJ, exist_ok=True)
with open(os.path.join(PRJ, ".gitignore"), "w") as _f:
    _f.write(
        "# transient csim artifacts (regenerated by build_eva_systemc.py / cosim_eva_systemc.py)\n"
        "sim\ncsim_sim\n*.data\n*.o\n"
    )

# Scheduled build: apply the EVA schedule (pipeline the node kernel at II=1 +
# register-file partition), then emit through SystemC. The SystemC emitter
# subclasses the Catapult emitter, which turns the s.pipeline `pipeline_ii`
# loop attribute into `#pragma hls_pipeline_init_interval`. (Catapult ignores
# array_partition, so partition_rf mainly matters for the Vitis path.)
s = e.get_scheduled_eva(float16, pipeline_node=True, partition_rf=True)
mod = s.build(target="systemc", mode="csim", project=PRJ)
print("=== EVA SystemC emit OK (scheduled: pipeline II=1 + partition_rf) ->", PRJ)

kp = os.path.join(PRJ, "kernel.cpp")
if os.path.exists(kp):
    src = open(kp).read()
    print(f"kernel.cpp lines={src.count(chr(10))}  "
          f"SC_MODULEs={src.count('SC_MODULE(')}  AlloFifo={src.count('AlloFifo<')}")
    print(f"pipeline pragmas: hls_pipeline_init_interval="
          f"{src.count('hls_pipeline_init_interval')}  "
          f"hls_unroll={src.count('hls_unroll')}")
    print("Compile + run:  cd generated && ./csim.sh")
