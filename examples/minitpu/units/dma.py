def _seed_vcd():
    """Build and run ``tb_dma_bandwidth`` unchanged with a VCD dump, cached
    beside vcd_seed's; it prints a bare ``PASS``, so vcd_seed's own
    ``PASS <tb>`` check does not apply."""
    from examples.minitpu.harness import vcd_seed  # noqa: F401
    home = rtl.minitpu_home()
    cache = os.environ.get("MINITPU_HARNESS_CACHE", os.path.join(home, ".build", "allo_harness"))
    h = hashlib.sha256(SEED_TB.encode())
    for s in SEED_SOURCES + [f"tb/{SEED_TB}.sv"]:
        with open(os.path.join(home, s), "rb") as f:
            h.update(f.read())
    d = os.path.join(cache, f"seed-{SEED_TB}-{h.hexdigest()[:12]}")
    vcd = os.path.join(d, "dump.vcd")
    if os.path.exists(vcd):
        return vcd
    os.makedirs(d, exist_ok=True)
    top = os.path.join(d, "u4_seed_top.sv")
    with open(top, "w", encoding="utf-8") as f:
        f.write("`timescale 1ns/1ps\nmodule u4_seed_top;\n  tb_dma_bandwidth tb();\n"
                f'  initial begin $dumpfile("{vcd}"); $dumpvars(0, tb.dut); end\nendmodule\n')
    cmd = ([shutil.which("verilator") or "verilator", "--binary", "--timing", "--trace",
            "-Wno-fatal", "-j", "8", "--top-module", "u4_seed_top", "--Mdir", d]
           + [os.path.join(home, s) for s in SEED_SOURCES]
           + [os.path.join(home, "tb", f"{SEED_TB}.sv"), top])
    r = subprocess.run(cmd, cwd=home, env=dict(os.environ, CXX=rtl._cxx()),
                       capture_output=True, text=True)
    exe = os.path.join(d, "Vu4_seed_top")
    if r.returncode != 0 or not os.path.exists(exe):
        raise RuntimeError(f"seed build failed:\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
    r = subprocess.run([exe], cwd=d, capture_output=True, text=True, timeout=900)
    if r.returncode != 0 or "PASS" not in r.stdout:
        if os.path.exists(vcd):
            os.remove(vcd)
        raise RuntimeError(f"{SEED_TB} did not pass:\n{r.stdout[-2000:]}")
    return vcd


def seeds():
    from examples.minitpu.harness import vcd_seed

    vcd = _seed_vcd()
    u = INSTANCES["bw"]
    ins = [p for p, _ in u.inputs]
    outs = [rtl.out_spec(o) for o in u.outputs]
    ch = vcd_seed.read_vcd(vcd, "tb.dut", ["clk"] + ins + [o[0] for o in outs])
    edges = [t for (t, v), (_, pv) in zip(ch["clk"][1:], ch["clk"][:-1]) if v == 1 and pv == 0]

    def before(sig, times):
        out, cur, i, c = [], 0, 0, ch[sig]
        for t in times:
            while i < len(c) and c[i][0] < t:
                cur = c[i][1]
                i += 1
            out.append(cur)
        return out

    times = edges + [float("inf")]
    cmd = {p: before(p, times) for p in ins}
    seen = {p: before(p, times) for p, _, _ in outs}
    return [(SEED_TB, "bw", cmd, seen, True)]


