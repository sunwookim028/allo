"""U4: ``dma``, MiniTPU's core DMA engine, against a cycle model.

``src/core/dma/dma.sv``: two descriptor channels (IDLE -> PENDING -> ACTIVE
-> DONE, done sticky until a W1C clear), one issue engine serving the
PENDING channels round-robin, a credit counter of ``OUTSTANDING`` bursts, an
in-order order FIFO, a ``LANDING_DEPTH`` landing FIFO that drains response
beats into VMEM (loads) or retires them (stores), a bridge-silence watchdog,
and sticky error/statistics registers. A stride-1 descriptor fuses rows into
bursts of up to 128 DM words, cut at every 4 KiB page; any other stride is
one word per burst. A store reads each beat from VMEM (``vmem_rd_en``, data
``VMEM_DMA_READ_LATENCY`` = 2 cycles later) before sending it.

**Closed loop: open-loop traces from a Python bridge (choice (b)).** The
response side (``dm_rsp_*``) and the VMEM read data depend on the requests
the DMA made. The traces are generated by running the cycle model
(``harness/ref_ctrl_dma.py``) together with a Python model of an in-order
bridge (programmable round trip, response gaps, ``dm_req_ready``
backpressure, SLVERR injection, a dropped response for the watchdog, late
stale beats) and a 2-cycle VMEM read pipe; the inputs it produced are then the
command trace, replayed on the RTL unchanged. No RTL is added (no fixture), so
the DUT is ``dma.sv`` alone and the seeded ``tb_dma_bandwidth`` replays on
the same unit. If the model and the RTL diverge, the RTL meets responses the
model expected; the divergence still shows as a REF-DIFF at its first cycle.

Instances: ``core`` (the parameters ``minitpu_core.sv`` builds: 2 channels,
``OUTSTANDING`` 2, ``LANDING_DEPTH`` 8, watchdog 1024), ``o1``
(``OUTSTANDING`` 1), ``o4`` (``OUTSTANDING`` 4, ``LANDING_DEPTH`` 4: the
equality edge of the ``>=`` rule), ``bw`` (``TIMEOUT_CYCLES`` 0, as
``tb_dma_bandwidth`` builds it; carries that tb's seed).
"""

