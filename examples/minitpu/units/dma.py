def _unit(p):
    return rtl.RtlUnit(
        top="dma",
        sources=SOURCES,
        inputs=list(INPUTS),
        outputs=[(q, w, "pre") for q, w in OUTPUTS],
        shape="trace",
        clk="clk",
        rst_n="rst_n",
        params={"DMA_CHANNEL_COUNT": p["channels"], "OUTSTANDING": p["outstanding"],
                "TIMEOUT_CYCLES": p["timeout"], "LANDING_DEPTH": p["landing"],
                "M_AXI_DATA_WIDTH": 256},
        assertions=True,
    )


