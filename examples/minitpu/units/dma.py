def _first_change(col, event):
    vals = rtl.unpack(col)
    for i in range(event, len(vals)):
        if vals[i] != vals[event - 1]:
            return i - event
    return None


def _run(inst, cmd):
    u = INSTANCES[inst]
    return rtl.run_trace(u, {p: rtl.pack(cmd[p], w) for p, w in u.inputs})


def probes(inst):
    """``[(label, declared, measured)]`` measured on the RTL, no reference."""
    res = []
    rng = rng_for("dma-probe", inst)
    # desc_valid -> desc_accept (combinational: 0 edges)
    p = Program(inst, rng, Bridge(rng, rtt=(4, 4), p_gap=0.0))
    p.idle(4)
    ev = len(p.rows)
    p.desc(0, 0, 0x40, 3, 0x100, 1)
    p.drain()
    r = _run(inst, p.cmd())
    res.append(("desc_valid -> desc_accept (comb)", 0, _first_change(r["desc_accept"], ev)))
    res.append(("accept -> first dm_req_valid", 2, _first_change(r["dm_req_valid"], ev)))
    # last response beat -> dma_channel_done
    cmd = p.cmd()
    last = max(i for i, (v, l) in enumerate(zip(cmd["dm_rsp_valid"], cmd["dm_rsp_last"])) if v and l)
    res.append(("last response beat -> dma_channel_done", 2, _first_change(r["dma_channel_done"], last)))
    # done -> clear -> a held descriptor on that channel is accepted
    p = Program(inst, rng, Bridge(rng, rtt=(4, 4), p_gap=0.0))
    p.desc(0, 0, 0x40, 3, 0x100, 1)
    while not p.m.done & 1:
        p.cycle()
    p.idle(3)
    ev = len(p.rows)
    p.cycle(clear_channel_done=1, desc_valid=1, desc_channel=0, desc_rows=3, desc_stride=1)
    d = dict(desc_valid=1, desc_channel=0, desc_rows=3, desc_stride=1)
    while not p.cycle(**d)["desc_accept"]:
        pass
    p.drain()
    r = _run(inst, p.cmd())
    res.append(("clear_channel_done -> held descriptor accepted", 1, _first_change(r["desc_accept"], ev)))
    # store: vmem_rd_en -> the cycle whose vmem_rd_data is captured, by function:
    # a marker on exactly one offset k after the read; which k reaches dm_req_wdata
    got = None
    for k in (1, 2, 3):
        p = Program(inst, rng, Bridge(rng, rtt=(4, 4), p_gap=0.0))
        p.desc(0, 1, 0x40, 0, 0x100, 1)
        cmd = p.cmd()
        # find the read, rebuild the trace with junk VMEM data and the marker at +k
        while True:
            o = p.cycle()
            if o["vmem_rd_en"]:
                rd = len(p.rows) - 1
                break
        p.drain()
        cmd = p.cmd()
        cmd["vmem_rd_data"] = [_word("probe-junk", t) for t in range(len(cmd["rst_n"]))]
        marker = (1 << 255) | 0xC0FFEE
        cmd["vmem_rd_data"][rd + k] = marker
        r = _run(inst, cmd)
        wd = rtl.unpack(r["dm_req_wdata"])
        wv = rtl.unpack(r["dm_req_valid"])
        if any(v and w == marker for v, w in zip(wv, wd)):
            got = k
    res.append(("store: vmem_rd_en -> captured vmem_rd_data (VMEM_DMA_READ_LATENCY)", 2, got))
    return res


