def make_llm(tool: AlloSpecTool, title: str) -> IsaOpenCodeLLM:
    provider, _, model_id = MODEL.partition("/")
    if TEST_BASE_URL:
        additional = [AdditionalModelProvider(
            id=provider, models=[model_id], base_url=TEST_BASE_URL,
            api_key="unused")]
    else:
        additional = [vertex_provider(provider, model_id)]
    return IsaOpenCodeLLM(
        model=MODEL,
        system_message=CODESIGN_MESSAGE if tool.codesign else SYSTEM_MESSAGE,
        timeout_seconds=2400,
        # CHIA's default of 3 silently re-runs a whole prompt after a timeout;
        # in the smoke run that retry began on a blocked tool server and paid
        # for a session that could see no tools. One attempt, and the loop
        # decides what happens next.
        retries=1,
        additional_providers=additional,
        # opencode's own file and shell tools are denied: the MCP tools are the
        # agent's only capability, so it has no path to a frozen file.
        config={"*": "deny", f"{tool.name}_*": "allow"},
        # Every session this worker opens carries the run's tag, which is how
        # its spend is found -- including a call that timed out and so returned
        # no session id.
        extra_cli_args=["--title", title],
    )


def vertex_provider(provider: str, model_id: str) -> AdditionalModelProvider:
    if not PROJECT:
        raise RuntimeError("Set GOOGLE_CLOUD_PROJECT before running the Vertex AI agent.")
    if provider != "google-vertex" or not model_id:
        raise ValueError("TINYTPU_OPENCODE_MODEL must be google-vertex/<model-id>.")
    return AdditionalModelProvider(
        id="google-vertex",
        npm="@ai-sdk/google-vertex",
        name="Google Vertex AI",
        models=[model_id],
        options={"project": PROJECT, "location": LOCATION},
    )


RATE_LIMIT_RETRIES = 6
RATE_LIMIT_BACKOFF = 45.0


class BudgetExhausted(Exception):
    pass


class Budget:
    """THIS RUN's spend cap, read from opencode's DB: the sessions titled with
    the run's tag (every worker's) plus the ids this loop saw returned.

    Never `usage`, and never the whole account. `usage` reports $0 for a call
    that timed out and was billed; the account sums whatever else is running on
    this host, which is how a $15 cap once read $15.82 with only $4.46 of it
    the run's own and stopped a search after 2 of 5 iterations. `billable` is
    what pre-flight decided -- the scripted test model on loopback cannot be
    billed at all."""

    def __init__(self, cap_usd: float, t0_ms: int, run_tag: str, worker: str,
                 billable: bool = True):
        self.cap, self.t0, self.run_tag = cap_usd, t0_ms, run_tag
        self.billable = billable
        #: Every session this worker opens is titled with this (loop.py passes
        #: `--title` to opencode), and the run's prefix finds every worker's.
        self.title = f"{run_tag} [{worker}]"
        self.sessions: set[str] = set()
        self.largest_call = DEFAULT_CALL_USD

    def note_session(self, session_id):
        if session_id:
            self.sessions.add(str(session_id))

    def _run(self) -> dict:
        if not self.billable:
            return {"usd": 0.0, "sessions": {}}
        return run_spend(self.run_tag + " ", self.t0, self.sessions)

    def spent(self) -> float:
        return self._run()["usd"]

    def mine(self) -> dict:
        """This worker's sessions and what each has cost so far."""
        if not self.billable:
            return {}
        return run_spend(self.title, self.t0, self.sessions)["sessions"]

    def check(self, what: str):
        run = self._run()
        if run["usd"] + self.largest_call > self.cap:
            raise BudgetExhausted(
                f"not starting {what}: this run has spent ${run['usd']:.2f} over "
                f"{len(run['sessions'])} session(s) + next call "
                f"~${self.largest_call:.2f} would pass the ${self.cap:.2f} cap")
        return run["usd"]

    def observe(self, usd: float):
        self.largest_call = max(self.largest_call, usd)


def ask(llm, tool, prompt, budget: Budget, what: str, calls: list):
    for attempt in range(RATE_LIMIT_RETRIES + 1):
        budget.check(what)
        before = budget.mine()
        started = time.time()
        try:
            response = get(
                llm.prompt.options(resources={"opencode_creds": 1}).chia_remote(
                    llm, prompt, [tool]))
        except RateLimitError:
            if attempt == RATE_LIMIT_RETRIES:
                raise
            delay = RATE_LIMIT_BACKOFF * (2**attempt) * (0.5 + random.random())
            print(f"  rate limited; retrying in {delay:.0f}s", flush=True)
            time.sleep(delay)
            continue
        usage = dict(getattr(response, "usage", None) or {})
        # Money comes from opencode's DB, never from `usage`: a call that timed
        # out returns no session id and reports $0, and was billed.
        sid = getattr(response, "session_id", None)
        budget.note_session(sid)
        new = {s: c for s, c in budget.mine().items() if s not in before}
        usd = round(sum(new.values()), 4)
        budget.observe(usd)
        calls.append({"what": what, "seconds": round(time.time() - started, 1),
                      "session_id": sid, "sessions": sorted(new), "usd": usd,
                      "completed": bool(getattr(response, "success", True)),
                      "num_turns": usage.get("num_turns")})
        print(f"  [{what}] ${usd:.2f} over {len(new)} session(s), "
              f"{usage.get('num_turns', '?')} turns, {time.time() - started:.0f}s; "
              f"run total ${budget.spent():.2f}", flush=True)
        return response
    raise RuntimeError("unreachable")


def summarize(v: dict) -> str:
    if not v.get("ok"):
        return f"FAILED at {v.get('stage')}"
    per = ", ".join(f"{s}={c}" for s, c in v["cycles"].items())
    syn = v.get("synth", {})
    area = syn.get("area", {})
    text = (f"cosim total={v['total_cycles']} [{per}] est_clock="
            f"{syn.get('estimated_ns')}ns LUT={area.get('lut')} FF={area.get('ff')} "
            f"DSP={area.get('dsp')} BRAM18K={area.get('bram_18k')}")
    ms = v.get("mapspace", {}).get("shapes", {})
    if ms:
        text += "  |  " + "; ".join(
            f"{s}: {d.get('encodable')}/{d.get('total')} nests, chose "
            f"{d.get('chosen')}" for s, d in sorted(ms.items()))
    return text


#: Resource terms of the objective. Reported per candidate, never summed with
#: cycles: "2.3x the block RAM for 9% of the cycles" is a trade, not a win, and
#: it has already happened once on this design (run 1's dma_ld widening took
#: BRAM18K from 42 to 98 for -59 cycles at the largest shape).
RESOURCES = ("bram_18k", "dsp", "ff", "lut", "uram")


def classify(base: dict, cand: dict) -> tuple[str, dict]:
    """win / trade / regression, on the TWO-term objective. Frozen rule.

    A `win` is a Pareto improvement: no shape's cosim cycle count is higher, at
    least one is lower, and no resource term grew. A `trade` lowers the total
    cycles but pays for it somewhere -- more of some resource, or a regression
    at another shape. `regression` does not lower the total at all.

    The loop still tracks its best by total cycles, so the search can move; the
    classification is what gets reported, because collapsing the pair into one
    number is exactly the mistake this loop is supposed to avoid.
    """
    cyc_b, cyc_c = base.get("cycles", {}), cand.get("cycles", {})
    shapes = sorted(set(cyc_b) & set(cyc_c))
    dcyc = {s: cyc_c[s] - cyc_b[s] for s in shapes}
    ab = base.get("synth", {}).get("area", {})
    ac = cand.get("synth", {}).get("area", {})
    dres = {r: ac.get(r, 0) - ab.get(r, 0) for r in RESOURCES
            if r in ab or r in ac}
    detail = {"delta_cycles": dcyc, "delta_resources": dres,
              "delta_total_cycles": sum(dcyc.values())}
    if sum(dcyc.values()) >= 0:
        return "regression", detail
    if all(d <= 0 for d in dcyc.values()) and all(d <= 0 for d in dres.values()):
        return "win", detail
    return "trade", detail


def _record(log_path: Path, entry: dict) -> None:
    with log_path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(entry, sort_keys=True) + "\n")


def frozen_is_clean() -> str | None:
    p = subprocess.run(["git", "status", "--porcelain", "--", *FROZEN_PATHS],
                       cwd=REPO_ROOT, capture_output=True, text=True)
    dirty = [l for l in p.stdout.splitlines() if l.strip()]
    return "\n".join(dirty) or None


def seed_spec(spec_dir: Path) -> None:
    """A private copy of the writable design files, from git HEAD.

    The spec directory mirrors the package: `design.EDITABLE` names paths, not
    bare names, since the hardware is eight units under `ip/units/`."""
    spec_dir.mkdir(parents=True, exist_ok=True)
    for rel in EDITABLE:
        target = spec_dir / rel
        if not target.exists():
            blob = subprocess.run(
                ["git", "show", f"HEAD:examples/tinytpu/{rel}"],
                cwd=REPO_ROOT, capture_output=True, check=True).stdout
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(blob)


