"""A CHIA propose -> gate -> cosim -> keep-or-rewind loop for TinyTPU-isa.

Each iteration asks the agent for one candidate edit to `microarch_isa.py`
and/or `isa_dsl.py` in this worker's private spec directory. The harness then
scores it itself with the frozen evaluator (`evaluate.py`) -- it never takes the
agent's word or the agent's own tool output:

  gate   bench_isa.py + main's stress_isa.py   (functional, ~15 s; each
         verdict vouched for by gate_runner.py, not read from stdout)
  score  cosim.py at the search shapes           (RTL cosim cycles, ~2-4 min)

A candidate is kept only if it passes both and strictly lowers the summed cosim
cycles; otherwise the spec is rewound and the next iteration is told why. What
it is lowered against is measured, not looked up: iteration 0 scores the
unmodified design in this environment, records the design's blob ids with it,
and cross-checks it against the published numbers (`control.py`) so that a
toolchain that moved is loud at the start of the run rather than implicit in
every verdict after it.

A spend cap is enforced before every model call: if THIS RUN's spend
(opencode's own DB, over the sessions titled with the run's tag, every worker)
plus the largest single call seen so far would exceed the cap, the loop stops
proposing. Another track's spend on the same account is not this run's -- a cap
that summed the account stopped run 2 after 2 of its 5 iterations (`spend.py`).
"""

