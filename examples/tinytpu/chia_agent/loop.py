def mapspace_text(v: dict) -> str:
    ms = v.get("mapspace", {}).get("shapes", {})
    if not ms:
        return "  (no mapspace report)"
    out = []
    for s, d in sorted(ms.items()):
        out.append(f"  {s}: {d.get('encodable')} of {d.get('total')} nests "
                   f"encodable; mapper chose {d.get('chosen')} "
                   f"({d.get('fetches')} instruction fetches, {d.get('words')} of "
                   f"{d.get('imem_size')} imem words). Refused:")
        for cause, n in sorted(d.get("refused", {}).items(), key=lambda kv: -kv[1]):
            out.append(f"      {n:6d}  {cause}")
    return "\n".join(out)


