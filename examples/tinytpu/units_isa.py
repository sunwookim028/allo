@df.unit(mapping=[1])
def sequencer(
    c_dld: Stream[UInt(64), QD],
    c_spm: Stream[UInt(64), QD],
    c_vru: Stream[UInt(64), QD],
    c_acc: Stream[UInt(64), QD],
    c_dst: Stream[UInt(64), QD],
    dram_imem: UInt(64)[IMEM_SIZE],
):
    # The whole program comes on-chip in one constant-trip contiguous burst,
    # and every fetch after it is an on-chip read. Fetched in place,
    # `dram_imem[NHDR + pc * IWORDS]` is a data-dependent address that Vitis
    # can only burst two words at a time: II=13 on the fetch loop.
    program: UInt(64)[IMEM_SIZE]
    for group in range(IMEM_SIZE // 8):
        with allo.meta_for(8) as word_in_group:
            program[8 * group + word_in_group] = dram_imem[8 * group + word_in_group]

    header: UInt(64) = program[0]
    n_instr: int32 = header[0:16]

    c_dld.put(program[1])
    c_dld.put(program[7])
    c_spm.put(program[2])
    c_spm.put(program[4])
    c_vru.put(program[3])
    c_acc.put(program[5])
    c_dst.put(program[6])

    loop_body: int32[LOOP_DEPTH] = 0
    loop_iter: int32[LOOP_DEPTH] = 0
    loop_trip: int32[LOOP_DEPTH] = 0
    live_iv: int32[LOOP_DEPTH] = 0
    loop_sp: int32 = 0
    pc: int32 = 0
    running: int32 = 1

    while running == 1:
        control_word: UInt(64) = program[NHDR + pc * IWORDS]
        agu_word: UInt(64) = program[NHDR + pc * IWORDS + 1]
        op: int32 = control_word[0:6]
        nr: int32 = control_word[54:62]

        if op == OP_LOOP:
            loop_body[loop_sp] = pc + 1
            loop_iter[loop_sp] = 0
            loop_trip[loop_sp] = nr
            live_iv[loop_sp] = 0
            loop_sp += 1
            pc += 1
        elif op == OP_ENDLOOP:
            next_iter: int32 = loop_iter[loop_sp - 1] + 1
            if next_iter < loop_trip[loop_sp - 1]:
                loop_iter[loop_sp - 1] = next_iter
                live_iv[loop_sp - 1] = next_iter
                pc = loop_body[loop_sp - 1]
            else:
                loop_sp -= 1
                pc += 1
        else:
            f0: int32 = control_word[6:18]
            f1: int32 = control_word[18:30]
            f2: int32 = control_word[30:42]
            f3: int32 = control_word[42:54]
            with allo.meta_for(AGU_TERMS) as term:
                target: int32 = agu_word[19 * term : 19 * term + 4]
                level: int32 = agu_word[19 * term + 4 : 19 * term + 7]
                stride: int32 = agu_word[19 * term + 7 : 19 * term + 19]
                offset: int32 = live_iv[level] * stride
                if target == AGU_F0:
                    f0 = f0 + offset
                if target == AGU_F1:
                    f1 = f1 + offset
                if target == AGU_F2:
                    f2 = f2 + offset
                if target == AGU_F3:
                    f3 = f3 + offset

            resolved: UInt(64) = control_word
            resolved[6:18] = f0
            resolved[18:30] = f1
            resolved[30:42] = f2
            resolved[42:54] = f3

            if op == OP_DMA_LD:
                c_dld.put(resolved)
                if f0 >= DMA_TO_VR:
                    c_vru.put(resolved)
                else:
                    c_spm.put(resolved)
            if op == OP_VLD:
                c_spm.put(resolved)
                c_vru.put(resolved)
            if op == OP_MM:
                # `spm` pushes one header word and T weight rows per `mm`, and
                # the array's row count travels in f1.
                spm_copy: UInt(64) = resolved
                spm_copy[54:62] = T + 1
                spm_copy[18:30] = nr
                c_spm.put(spm_copy)
                c_vru.put(resolved)
                c_acc.put(resolved)
            if op == OP_VADD:
                # `accu` takes two steps per `vadd` row.
                accu_copy: UInt(64) = resolved
                accu_copy[54:62] = nr * 2
                c_acc.put(accu_copy)
            if op == OP_VRELU:
                c_acc.put(resolved)
            if op == OP_VADDRELU:
                # Two sources, so two `accu` steps a row, as for `vadd`.
                fused_copy: UInt(64) = resolved
                fused_copy[54:62] = nr * 2
                c_acc.put(fused_copy)
            if op == OP_MVOUT:
                c_acc.put(resolved)
                c_dst.put(resolved)
            pc += 1

        if pc >= n_instr:
            running = 0


@df.unit(mapping=[1])
def dma_ld(
    c_dld: Stream[UInt(64), QD],
    dma2sp: Stream[UInt(VW), QD],
    dma2vr: Stream[UInt(VW), QD],
    dram_a: int8[MAXDIM * MAXDIM],
    dram_b: int8[MAXDIM * MAXDIM],
):
    count_word: UInt(64) = c_dld.get()
    n_row: int32 = count_word[0:16]
    span_word: UInt(64) = c_dld.get()
    a_rows: int32 = span_word[0:16]
    b_rows: int32 = span_word[16:32]

    # One variable-length burst per matrix, covering exactly the DRAM rows the
    # program names, staged on chip. TWO MEASURED NEGATIVES guard this loop,
    # both in dev/records/tinytpu/measured_negatives.rst -- read them before
    # changing it:
    #   1. merging the two bursts into one bounded by max(a_rows, b_rows)
    #      halves the burst time and moves NO cycles;
    #   2. the "strided costs 4x" case for staging here at all is stale. A
    #      flat per-row `m_axi` loop now closes at II=1, so the mirror is
    #      defended on amortising a re-read, never on burst shape.
    #
    # DMA_WORDS is the burst width in packed words an iteration; 1 is the
    # shipped loop, and the `meta_for` unrolls inside a runtime loop so the
    # trip count stays runtime data. It stays a parameter rather than landing
    # because it was found at `-m_axi_latency 0`, and a change whose whole
    # benefit is wider bursts can grow or vanish with memory latency.
    a_onchip: UInt(VW)[MAXDIM * WPR + DMA_WORDS]
    b_onchip: UInt(VW)[MAXDIM * WPR + DMA_WORDS]
    a_groups: int32 = (a_rows * WPR + (DMA_WORDS - 1)) // DMA_WORDS
    for a_group in range(a_groups):
        with allo.meta_for(DMA_WORDS) as a_word:
            packed_a: UInt(VW) = 0
            with allo.meta_for(T) as a_lane:
                a_value: int8 = dram_a[(a_group * DMA_WORDS + a_word) * T + a_lane]
                packed_a[8 * a_lane : 8 * (a_lane + 1)] = a_value
            a_onchip[a_group * DMA_WORDS + a_word] = packed_a
    b_groups: int32 = (b_rows * WPR + (DMA_WORDS - 1)) // DMA_WORDS
    for b_group in range(b_groups):
        with allo.meta_for(DMA_WORDS) as b_word:
            packed_b: UInt(VW) = 0
            with allo.meta_for(T) as b_lane:
                b_value: int8 = dram_b[(b_group * DMA_WORDS + b_word) * T + b_lane]
                packed_b[8 * b_lane : 8 * (b_lane + 1)] = b_value
            b_onchip[b_group * DMA_WORDS + b_word] = packed_b

    route: int32 = 0
    dram_row0: int32 = 0
    col_block: int32 = 0
    instr_rows: int32 = 0
    row: int32 = -1  # advanced at the top: hoisting this holds II=1
    for work in range(n_row):
        row += 1
        if row >= instr_rows:
            # Only `dma_ld` reaches this queue, so there is no opcode test.
            word: UInt(64) = c_dld.get()
            route = word[6:18]
            dram_row0 = word[18:30]
            col_block = word[30:42]
            instr_rows = word[54:62]
            row = 0
        packed: UInt(VW) = 0
        if (route & DMA_SRC_B) == 0:
            packed = a_onchip[(dram_row0 + row) * WPR + col_block]
        else:
            packed = b_onchip[(dram_row0 + row) * WPR + col_block]
        if route >= DMA_TO_VR:
            dma2vr.put(packed)
        else:
            dma2sp.put(packed)


@df.unit(mapping=[1])
def spm(
    c_spm: Stream[UInt(64), QD],
    dma2sp: Stream[UInt(VW), QD],
    sp2vr: Stream[UInt(VW), QD],
    wcol: Stream[UInt(VW), QD][T],
):
    spad: UInt(VW)[SPAD_ROWS]
    count_word: UInt(64) = c_spm.get()
    n_row: int32 = count_word[0:16]
    array_counts_word: UInt(64) = c_spm.get()
    array_counts: UInt(VW) = 0
    array_counts[0:32] = array_counts_word[0:32]  # mm count | mm rows << 16
    wcol[0].put(array_counts)
    op: int32 = 0
    f1: int32 = 0  # mm: the array's row count; vld: the spad row
    spad_base: int32 = 0
    instr_rows: int32 = 0
    row: int32 = -1  # advanced at the top: hoisting this holds II=1
    for work in range(n_row):
        row += 1
        if row >= instr_rows:
            word: UInt(64) = c_spm.get()
            op = word[0:6]
            f1 = word[18:30]
            spad_base = word[42:54]
            instr_rows = word[54:62]
            row = 0
        read_row: int32 = f1 + row
        if op == OP_MM:
            # row 0 is the header; rows 1..T are weight rows 0..T-1, row 0
            # first, so PE row i keeps the i-th word it sees.
            read_row = spad_base + row - 1
            if row == 0:
                read_row = spad_base
        if op == OP_DMA_LD:
            spad[spad_base + row] = dma2sp.get()
        else:
            # ONE spad read per iteration at a muxed address, which a dual-port
            # BRAM holds at II=1.
            loaded: UInt(VW) = spad[read_row]
            if op == OP_VLD:
                sp2vr.put(loaded)
            else:
                weight_word: UInt(VW) = loaded
                if row == 0:
                    header: UInt(VW) = 0
                    header[0:12] = f1
                    weight_word = header
                wcol[0].put(weight_word)


@df.unit(mapping=[1])
def vru(
    c_vru: Stream[UInt(64), QD],
    dma2vr: Stream[UInt(VW), QD],
    sp2vr: Stream[UInt(VW), QD],
    acol: Stream[UInt(VW), QD][T],
):
    count_word: UInt(64) = c_vru.get()
    n_word: int32 = count_word[0:16]
    vr: UInt(VW)[NVR]
    op: int32 = 0
    vr_base: int32 = 0  # mm: the activation rows; vld: the destination
    dma_base: int32 = 0
    instr_rows: int32 = 0
    row: int32 = -1  # advanced at the top: hoisting this holds II=1
    for work in range(n_word):
        row += 1
        if row >= instr_rows:
            word: UInt(64) = c_vru.get()
            op = word[0:6]
            vr_base = word[6:18]
            dma_base = word[42:54]
            instr_rows = word[54:62]
            row = 0
        # ONE vr read and ONE vr write per iteration, each at a muxed address
        # and the write from a muxed source: that is what holds II=1 in the
        # unit that used to be the critical one.
        if op == OP_MM:
            activation: UInt(VW) = vr[vr_base + row]
            acol[0].put(activation)
        else:
            write_row: int32 = vr_base + row
            if op == OP_DMA_LD:
                write_row = dma_base + row
            write_word: UInt(VW) = 0
            if op == OP_VLD:
                write_word = sp2vr.get()
            else:
                write_word = dma2vr.get()
            vr[write_row] = write_word


@df.unit(mapping=[T, T])
def wld(
    wcol: Stream[UInt(VW), QD][T],
    wrow: Stream[UInt(VW), QD][T, T],
    wq: Stream[UInt(32), 4][T, T],
):
    i, j = df.get_pid()
    counts_word: UInt(VW) = 0
    with allo.meta_if(j == 0):
        counts_word = wcol[i].get()
        with allo.meta_if(i != T - 1):
            wcol[i + 1].put(counts_word)
    with allo.meta_else():
        counts_word = wrow[i, j - 1].get()
    with allo.meta_if(j != T - 1):
        wrow[i, j].put(counts_word)
    n_mm: int32 = counts_word[0:16]
    trip_word: UInt(32) = 0
    trip_word[0:16] = counts_word[16:32]
    wq[i, j].put(trip_word)
    for mm in range(n_mm):
        header: UInt(VW) = 0
        with allo.meta_if(j == 0):
            header = wcol[i].get()
            with allo.meta_if(i != T - 1):
                wcol[i + 1].put(header)
        with allo.meta_else():
            header = wrow[i, j - 1].get()
        with allo.meta_if(j != T - 1):
            wrow[i, j].put(header)
        weight_word: UInt(VW) = 0
        with allo.meta_if(j == 0):
            weight_word = wcol[i].get()
            with allo.meta_for(T - 1 - i) as _forward:
                wcol[i + 1].put(wcol[i].get())
        with allo.meta_else():
            weight_word = wrow[i, j - 1].get()
        with allo.meta_if(j != T - 1):
            wrow[i, j].put(weight_word)
        pe_word: UInt(32) = 0
        pe_word[0:8] = weight_word[8 * j : 8 * (j + 1)]
        pe_word[8:20] = header[0:12]
        wq[i, j].put(pe_word)


@df.unit(mapping=[T, T])
def pe(
    acol: Stream[UInt(VW), QD][T],
    a_fwd: Stream[int8, QD][T, T],
    p_fwd: Stream[int32, QD][T, T],
    cw: Stream[UInt(AW), QD][T],
    wq: Stream[UInt(32), 4][T, T],
):
    i, j = df.get_pid()
    trip_word: UInt(32) = wq[i, j].get()
    n_wavefront_row: int32 = trip_word[0:16]
    weight: int8 = 0
    mm_rows: int32 = 0
    row: int32 = -1  # advanced at the top: hoisting this holds II=1
    for work in range(n_wavefront_row):
        row += 1
        if row >= mm_rows:
            pe_word: UInt(32) = wq[i, j].get()
            weight = pe_word[0:8]
            mm_rows = pe_word[8:20]
            row = 0
        activation: int8 = 0
        with allo.meta_if(j == 0):
            activation_word: UInt(VW) = acol[i].get()
            with allo.meta_if(i != T - 1):
                acol[i + 1].put(activation_word)
            activation = activation_word[8 * i : 8 * (i + 1)]
        with allo.meta_else():
            activation = a_fwd[i, j - 1].get()
        psum_north: int32 = 0
        with allo.meta_if(i > 0):
            psum_north = p_fwd[i - 1, j].get()
        # int8 x int8 -> int16 keeps this a narrow multiply; the operands bound
        # the product at 128*128 = 16384.
        activation16: int16 = activation
        weight16: int16 = weight
        psum: int32 = psum_north + activation16 * weight16
        with allo.meta_if(i != T - 1):
            p_fwd[i, j].put(psum)
        with allo.meta_else():
            # The bottom row assembles the packed result word as it travels
            # east, so the accumulator sees whole words and there is no T-way
            # fan-in.
            result_word: UInt(AW) = 0
            with allo.meta_if(j > 0):
                result_word = cw[j - 1].get()
            result_word[32 * j : 32 * (j + 1)] = psum
            cw[j].put(result_word)
        with allo.meta_if(j != T - 1):
            a_fwd[i, j].put(activation)


@df.unit(mapping=[1])
def accu(
    c_acc: Stream[UInt(64), QD],
    ac2sp: Stream[UInt(VW), QD],
    cw: Stream[UInt(AW), QD][T],
):
    ar: UInt(AW)[NAR]
    count_word: UInt(64) = c_acc.get()
    n_step: int32 = count_word[0:16]
    op: int32 = 0
    f0: int32 = 0  # mm/vadd/vrelu: destination; mvout: source
    f1: int32 = 0  # mm: destination; vadd/vrelu: first source
    f2: int32 = 0  # mm: accumulate flag; vadd: second source
    instr_steps: int32 = 0
    step: int32 = -1  # advanced at the top: hoisting this holds II=1
    vadd_first: UInt(AW) = 0  # vadd's first operand, held for one step
    for work in range(n_step):
        step += 1
        if step >= instr_steps:
            word: UInt(64) = c_acc.get()
            op = word[0:6]
            f0 = word[6:18]
            f1 = word[18:30]
            f2 = word[30:42]
            instr_steps = word[54:62]
            step = 0
        row: int32 = step
        phase: int32 = 0
        two_source: int32 = 0
        if op == OP_VADD:
            two_source = 1
        if op == OP_VADDRELU:
            two_source = 1
        if two_source == 1:
            row = step >> 1
            phase = step - (row << 1)
        read_row: int32 = f1 + row
        write_row: int32 = f0 + row
        if op == OP_MM:
            write_row = f1 + row
        if op == OP_MVOUT:
            read_row = f0 + row
        if two_source == 1:
            if phase == 1:
                read_row = f2 + row
        read_word: UInt(AW) = ar[read_row]
        write_word: UInt(AW) = 0
        do_write: int32 = 1
        if op == OP_MM:
            array_word: UInt(AW) = cw[T - 1].get()
            base: UInt(AW) = 0
            if f2 == 1:
                base = read_word
            with allo.meta_for(T) as lane:
                base_lane: int32 = base[32 * lane : 32 * (lane + 1)]
                array_lane: int32 = array_word[32 * lane : 32 * (lane + 1)]
                summed: int32 = base_lane + array_lane
                write_word[32 * lane : 32 * (lane + 1)] = summed
        elif op == OP_VADD:
            if phase == 0:
                vadd_first = read_word
                do_write = 0
            else:
                with allo.meta_for(T) as add_lane:
                    first: int32 = vadd_first[32 * add_lane : 32 * (add_lane + 1)]
                    second: int32 = read_word[32 * add_lane : 32 * (add_lane + 1)]
                    added: int32 = first + second
                    write_word[32 * add_lane : 32 * (add_lane + 1)] = added
        elif op == OP_VADDRELU:
            if phase == 0:
                vadd_first = read_word
                do_write = 0
            else:
                with allo.meta_for(T) as fuse_lane:
                    held: int32 = vadd_first[32 * fuse_lane : 32 * (fuse_lane + 1)]
                    arriving: int32 = read_word[32 * fuse_lane : 32 * (fuse_lane + 1)]
                    fused: int32 = held + arriving
                    if fused < 0:
                        fused = 0
                    write_word[32 * fuse_lane : 32 * (fuse_lane + 1)] = fused
        elif op == OP_VRELU:
            with allo.meta_for(T) as relu_lane:
                before: int32 = read_word[32 * relu_lane : 32 * (relu_lane + 1)]
                rectified: int32 = before
                if rectified < 0:
                    rectified = 0
                write_word[32 * relu_lane : 32 * (relu_lane + 1)] = rectified
        else:
            do_write = 0
            clipped_word: UInt(VW) = 0
            with allo.meta_for(T) as clip_lane:
                retiring: int32 = read_word[32 * clip_lane : 32 * (clip_lane + 1)]
                if retiring > 127:
                    retiring = 127
                if retiring < -128:
                    retiring = -128
                clipped: int8 = retiring
                clipped_word[8 * clip_lane : 8 * (clip_lane + 1)] = clipped
            ac2sp.put(clipped_word)
        if do_write == 1:
            ar[write_row] = write_word


@df.unit(mapping=[1])
def dma_st(
    c_dst: Stream[UInt(64), QD],
    ac2sp: Stream[UInt(VW), QD],
    dram_c: int8[MAXDIM * MAXDIM],
):
    count_word: UInt(64) = c_dst.get()
    n_row: int32 = count_word[0:16]
    dram_row0: int32 = 0
    col_block: int32 = 0
    instr_rows: int32 = 0
    row: int32 = -1  # advanced at the top: hoisting this holds II=1
    for work in range(n_row):
        row += 1
        if row >= instr_rows:
            # Only `mvout` reaches this queue, so there is no opcode test.
            word: UInt(64) = c_dst.get()
            dram_row0 = word[18:30]
            col_block = word[30:42]
            instr_rows = word[54:62]
            row = 0
        clipped_word: UInt(VW) = ac2sp.get()
        with allo.meta_for(T) as lane:
            lane_value: int8 = clipped_word[8 * lane : 8 * (lane + 1)]
            dram_c[(dram_row0 + row) * MAXDIM + col_block * T + lane] = lane_value


@df.region(
    deadlock_free_because=(
        "Every loop this netlist reports is an array channel a unit reads at "
        "one element and writes at another, which is a chain and not a loop; "
        "the index is a runtime value, so nothing static can tell them apart. "
        "Control is one-way: the sequencer sends and never receives. Queue "
        "depths are sized so no unit runs further ahead than QD, which cosim "
        "measures and no rule proves. See docs/source/designs/tinytpu_isa.rst."
    )
)
def tinytpu_ports(
    imem: UInt(64)[IMEM_SIZE],
    A: int8[MAXDIM * MAXDIM],
    B: int8[MAXDIM * MAXDIM],
    C: int8[MAXDIM * MAXDIM],
):
    # Deliberately NOT the design's names: a unit no longer has to agree with
    # the region it is wired into on a string.
    bus_c_dld: Stream[UInt(64), QD]
    bus_c_spm: Stream[UInt(64), QD]
    bus_c_vru: Stream[UInt(64), QD]
    bus_c_acc: Stream[UInt(64), QD]
    bus_c_dst: Stream[UInt(64), QD]
    bus_dma2sp: Stream[UInt(VW), QD]
    bus_dma2vr: Stream[UInt(VW), QD]
    bus_sp2vr: Stream[UInt(VW), QD]
    bus_ac2sp: Stream[UInt(VW), QD]
    bus_wcol: Stream[UInt(VW), QD][T]
    bus_wrow: Stream[UInt(VW), QD][T, T]
    bus_acol: Stream[UInt(VW), QD][T]
    bus_a_fwd: Stream[int8, QD][T, T]
    bus_p_fwd: Stream[int32, QD][T, T]
    bus_cw: Stream[UInt(AW), QD][T]
    bus_wq: Stream[UInt(32), 4][T, T]

    sequencer(
        c_dld=bus_c_dld,
        c_spm=bus_c_spm,
        c_vru=bus_c_vru,
        c_acc=bus_c_acc,
        c_dst=bus_c_dst,
        dram_imem=imem,
    )
    dma_ld(
        c_dld=bus_c_dld,
        dma2sp=bus_dma2sp,
        dma2vr=bus_dma2vr,
        dram_a=A,
        dram_b=B,
    )
    spm(
        c_spm=bus_c_spm,
        dma2sp=bus_dma2sp,
        sp2vr=bus_sp2vr,
        wcol=bus_wcol,
    )
    vru(
        c_vru=bus_c_vru,
        dma2vr=bus_dma2vr,
        sp2vr=bus_sp2vr,
        acol=bus_acol,
    )
    wld(
        wcol=bus_wcol,
        wrow=bus_wrow,
        wq=bus_wq,
    )
    pe(
        acol=bus_acol,
        a_fwd=bus_a_fwd,
        p_fwd=bus_p_fwd,
        cw=bus_cw,
        wq=bus_wq,
    )
    accu(
        c_acc=bus_c_acc,
        ac2sp=bus_ac2sp,
        cw=bus_cw,
    )
    dma_st(
        c_dst=bus_c_dst,
        ac2sp=bus_ac2sp,
        dram_c=C,
    )
