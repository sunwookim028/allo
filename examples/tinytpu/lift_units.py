"""Regenerate `units_isa.py` from the region `microarch_isa` composes.

`units_isa.py` is the design's eight kernels lifted to module level with their
streams declared as ports. It is generated rather than hand-copied so that
"the bodies are unchanged" stays true: this script takes each nested
`@df.kernel`'s body verbatim from the composed region's source
(`TPU.architecture.source()`, built from the `ip/` units) and only writes a
new signature for it.

    python examples/tinytpu/lift_units.py            # rewrite units_isa.py
    python examples/tinytpu/lift_units.py --check    # committed == generated?

`--check` is the enforcement behind the "GENERATED -- do not edit" header, and
it exists because that header had nothing behind it: `units_isa.py` had
silently lost a whole opcode arm (`vaddrelu`) that `ip/units/sequencer.py`
grew, and the one test that reads the file never issued that opcode. A
convention with no check is a convention that has already drifted.

The output is `black`-formatted here rather than by hand, so the bytes the
check compares are the bytes the generator produces.

`microarch_isa.py` and the `ip/` library remain the design. See
`docs/source/developer/stream_ports.rst`.
"""

import argparse
import ast
import os
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..")))

from allo.netlist import stream_uses  # noqa: E402

TARGET = os.path.join(HERE, "units_isa.py")
REGION = "tinytpu_isa"
PREFIX = "bus_"

PREAMBLE = '''# Copyright Allo authors. All Rights Reserved.
# SPDX-License-Identifier: Apache-2.0
# pylint: disable=unused-wildcard-import, wildcard-import, undefined-variable
"""TinyTPU-isa as eight units that declare their stream ports.

GENERATED by `lift_units.py` -- do not edit. The bodies are those of the
region `microarch_isa` composes from `ip/`, unchanged; only the signatures are
new.
Each kernel there reaches its streams by lexical name from the region it is
nested in, and each unit here names them in its own interface, so
`tinytpu_ports` is free to wire them under channel names the design does not
use -- which is the whole point, and what
`tests/dataflow/test_stream_ports_tinytpu.py` asserts.

`microarch_isa.py` remains the design, and `reproduce.sh` still measures it.
"""

import allo
import allo.dataflow as df
from allo.ir.types import Stream, UInt, int8, int16, int32
from examples.tinytpu.microarch_isa import TPU

'''

PREMISE = """

@df.region(
    deadlock_free_because=(
        "Every loop this netlist reports is an array channel a unit reads at "
        "one element and writes at another, which is a chain and not a loop; "
        "the index is a runtime value, so nothing static can tell them apart. "
        "Control is one-way: the sequencer sends and never receives. Queue "
        "depths are sized so no unit runs further ahead than QD, which cosim "
        "measures and no rule proves. See docs/source/designs/tinytpu_isa.rst."
    )
)
def tinytpu_ports(
    imem: UInt(64)[IMEM_SIZE],
    A: int8[MAXDIM * MAXDIM],
    B: int8[MAXDIM * MAXDIM],
    C: int8[MAXDIM * MAXDIM],
):
    # Deliberately NOT the design's names: a unit no longer has to agree with
    # the region it is wired into on a string.
"""


def kernels_of(region, text):
    channels = {
        statement.target.id: ast.unparse(statement.annotation)
        for statement in region.body
        if isinstance(statement, ast.AnnAssign) and statement.value is None
    }
    lifted = []
    for statement in region.body:
        if not isinstance(statement, ast.FunctionDef):
            continue
        decorator = statement.decorator_list[0]
        keywords = {keyword.arg: keyword.value for keyword in decorator.keywords}
        values = (
            [ast.unparse(element) for element in keywords["args"].elts]
            if "args" in keywords
            else []
        )
        ports = [name for name in channels if name in stream_uses(statement.body)]
        lifted.append(
            (statement, ast.unparse(keywords["mapping"]), values, ports, text)
        )
    return channels, lifted


def body_of(statement, text):
    lines = ast.get_source_segment(text, statement).splitlines()
    start = next(i for i, line in enumerate(lines) if line.rstrip().endswith(":")) + 1
    return textwrap.dedent("\n".join(lines[start:]))


def emit(channels, lifted, parameters):
    out = [PREAMBLE]
    out.extend(
        f"{name} = TPU.architecture.parameters[{name!r}]" for name in sorted(parameters)
    )
    out.append("")
    for statement, mapping, _, ports, text in lifted:
        parameters = [f"{name}: {channels[name]}" for name in ports]
        parameters += [ast.unparse(argument) for argument in statement.args.args]
        out.append(f"\n@df.unit(mapping={mapping})")
        out.append(f"def {statement.name}(")
        out.extend(f"    {parameter}," for parameter in parameters)
        out.append("):")
        out.extend(
            f"    {line}" if line.strip() else ""
            for line in body_of(statement, text).splitlines()
        )
        out.append("")
    out.append(PREMISE.rstrip("\n"))
    out.extend(
        f"    {PREFIX}{name}: {annotation}" for name, annotation in channels.items()
    )
    out.append("")
    for statement, _, values, ports, _ in lifted:
        wiring = [f"{name}={PREFIX}{name}" for name in ports]
        wiring += [
            f"{argument.arg}={value}"
            for argument, value in zip(statement.args.args, values)
        ]
        out.append(f"    {statement.name}(")
        out.extend(f"        {item}," for item in wiring)
        out.append("    )")
    return "\n".join(out) + "\n"


def formatted(source: str) -> str:
    """`black` applied in process, so generating and checking cannot disagree
    about formatting the way a separate CLI step can."""
    import black  # noqa: PLC0415  -- only this one call needs it

    return black.format_str(source, mode=black.Mode())


def generate():
    """`(text, lifted, channels)` -- what `units_isa.py` should contain."""
    from examples.tinytpu.microarch_isa import TPU  # noqa: PLC0415

    text = TPU.architecture.source()
    region = next(
        node
        for node in ast.parse(text).body
        if isinstance(node, ast.FunctionDef) and node.name == REGION
    )
    channels, lifted = kernels_of(region, text)
    return formatted(emit(channels, lifted, TPU.architecture.parameters)), lifted, channels


def report(lifted, channels):
    print(f"{TARGET}: {len(lifted)} units, {len(channels)} channels")
    for statement, mapping, values, ports, _ in lifted:
        print(
            f"  {statement.name:10s} mapping={mapping:8s} "
            f"{len(ports)} ports {ports} values={values}"
        )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="compare the committed file with the generated "
                             "one and exit 1 on any difference")
    args = parser.parse_args(argv)
    text, lifted, channels = generate()
    if not args.check:
        with open(TARGET, "w", encoding="utf-8") as handle:
            handle.write(text)
        report(lifted, channels)
        print("  now run tests/dataflow/test_stream_ports_tinytpu.py")
        return 0
    try:
        with open(TARGET, encoding="utf-8") as handle:
            committed = handle.read()
    except OSError as error:
        print(f"UNITS STALE: cannot read {TARGET}: {error}")
        return 1
    if committed != text:
        import difflib  # noqa: PLC0415  -- only this branch needs it

        diff = list(difflib.unified_diff(
            committed.splitlines(True), text.splitlines(True),
            "committed units_isa.py", "generated from ip/", n=2))
        print("".join(diff[:80]), end="")
        if len(diff) > 80:
            print(f"  ... {len(diff) - 80} more diff lines")
        print(f"\nUNITS STALE: {TARGET} is not what the design composes to. "
              f"It is generated -- run `python {os.path.relpath(__file__)}` "
              f"rather than editing it.")
        return 1
    report(lifted, channels)
    print("  UNITS OK: units_isa.py is byte-identical to what ip/ composes to")
    return 0


if __name__ == "__main__":
    sys.exit(main())
