"""Generate the Wire-port form of a U1 unit variant, from the unit's own text.

    python gen_wire.py <unit> <variant> [<out_dir>]   (from the worktree root)

The pilot's ``variants.py:wire`` hand-wrote ``vpu_bf16_add`` as
``src -> Wire x2 -> add -> Wire -> sink`` so that the synthesized kernel
(``synth_top=<kernel>_0``) has plain ``sc_in``/``sc_out`` ports: the port shape
of a MiniTPU unit. Here the kernel body is **copied by text** from the unit's
variant (``inspect.getsource``), with only the ports changed:

* each input array read ``<p>[i]`` becomes a local ``<p>_w`` read once from a
  ``Wire`` at the top of the loop body,
* the output store ``<out>[i] = <expr>`` becomes ``wc.put(<expr>)``,
* ``for i in range(n)`` becomes ``for _ in range(n)`` (the pilot's loop name,
  so ``s.pipeline("<kernel>_0:_")``),

and nested ``def``\\ s in the kernel and lines before ``@df.region()`` in the
factory are kept. The generated module ``wire_<unit>_<variant>.py`` imports
the unit module's names, so reused functions (``add_bits``, ``mul_bits``,
``_engines``) are the unit's own. Bit-exactness of the result is checked in
Verilator like every other RTL here, so a transcription error would show.
"""
import importlib, inspect, os, re, sys, textwrap

sys.path.insert(0, os.getcwd())

unit, variant = sys.argv[1], sys.argv[2]
out_dir = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "wire")
u = importlib.import_module(f"examples.minitpu.units.{unit}")
fac = u.VARIANTS[variant][0]
if fac.__name__ == "<lambda>":
    raise SystemExit("lambda variant: name its factory instead")
src = textwrap.dedent(inspect.getsource(fac))
lines = src.splitlines()
sig = lines[0]
assert sig.startswith("def "), sig
i_reg = next(k for k, l in enumerate(lines) if l.strip() == "@df.region()")
pre = [l for l in lines[1:i_reg]]
# the kernel: the def after "@df.kernel(" inside the region
i_k = next(k for k, l in enumerate(lines) if l.strip().startswith("@df.kernel("))
kdef = lines[i_k + 1]
m = re.match(r"(\s*)def (\w+)\((.*)\):\s*$", kdef)
kind, kname, params = m.group(1), m.group(2), m.group(3)
ps = [(p.split(":")[0].strip(), p.split(":")[1].strip()) for p in params.split(", ")]
ps = [(p, re.sub(r"\[n\]$", "", t)) for p, t in ps]
ins, (outp, outt) = ps[:-1], ps[-1]
body = []
for l in lines[i_k + 2:]:
    if l.strip() and (len(l) - len(l.lstrip())) <= len(kind):
        break
    body.append(l)
body_ind = len(kind) + 4
# split the kernel body into nested defs (kept) and the "for i in range(n):" loop
i_for = next(k for k, l in enumerate(body) if l.strip() == "for i in range(n):"
             and len(l) - len(l.lstrip()) == body_ind)
nested = body[:i_for]
loop = body[i_for + 1:]
loop_ind = body_ind + 4
loop_txt = "\n".join(loop)
for p, _ in ins:
    loop_txt = re.sub(rf"\b{p}\[i\]", f"{p}_w", loop_txt)
loop_txt, k = re.subn(rf"^(\s*){outp}\[i\] = (.*)$", r"\1wc.put(\2)", loop_txt, flags=re.M)
assert k == 1, f"expected one store to {outp}[i], found {k}"
assert "[i]" not in loop_txt, "an indexed access left: not a one-vector body"

W = ["wa", "wb", "wd", "we"][: len(ins)]
R = " " * 4
out = [f"# Generated by gen_wire.py from examples.minitpu.units.{unit}.{fac.__name__}"
       f" (variant {variant!r}); do not edit.",
       "import allo.dataflow as df",
       "from allo.ir.types import *  # noqa: F401,F403",
       f"from examples.minitpu.units.{unit} import *  # noqa: F401,F403",
       f"from examples.minitpu.units import {unit} as _u",
       "for _k in dir(_u):",
       "    if _k.startswith('_') and not _k.startswith('__'):",
       "        globals()[_k] = getattr(_u, _k)",
       "",
       "",
       re.sub(r"^def \w+\(", "def wire(", sig)]
out += pre
args = ", ".join(f"{p.upper()}_: {t}[n]" for p, t in ins) + f", {outp.upper()}_: {outt}[n]"
out.append(R + "@df.region()")
out.append(R + f"def top({args}):")
for w, (p, t) in zip(W, ins):
    out.append(R * 2 + f"{w}: Wire[{t}]")
out.append(R * 2 + f"wc: Wire[{outt}]")
out.append("")
out.append(R * 2 + f"@df.kernel(mapping=[1], args=[{', '.join(p.upper() + '_' for p, _ in ins)}])")
out.append(R * 2 + f"def src({', '.join(f'{p}: {t}[n]' for p, t in ins)}):")
out.append(R * 3 + "for i in range(n):")
for w, (p, _) in zip(W, ins):
    out.append(R * 4 + f"{w}.put({p}[i])")
out.append("")
out.append(R * 2 + "@df.kernel(mapping=[1], args=[])")
out.append(R * 2 + f"def {kname}():")
out += [textwrap.indent(textwrap.dedent("\n".join(nested)), R * 3)] if any(x.strip() for x in nested) else []
out.append(R * 3 + "for _ in range(n):")
for w, (p, t) in zip(W, ins):
    out.append(R * 4 + f"{p}_w: {t} = {w}.get()")
out.append(textwrap.indent(textwrap.dedent(loop_txt), R * 4))
out.append("")
out.append(R * 2 + f"@df.kernel(mapping=[1], args=[{outp.upper()}_])")
out.append(R * 2 + f"def sink({outp}: {outt}[n]):")
out.append(R * 3 + "for i in range(n):")
out.append(R * 4 + f"{outp}[i] = wc.get()")
out.append("")
out.append(R + "return top")
os.makedirs(out_dir, exist_ok=True)
path = os.path.join(out_dir, f"wire_{unit}_{variant}.py")
open(path, "w").write("\n".join(out) + "\n")
print(f"WROTE {path}: kernel {kname}_0, inputs {[p for p, _ in ins]}, output {outp}")
