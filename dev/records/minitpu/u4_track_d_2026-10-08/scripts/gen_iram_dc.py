"""DC stand-in for ``sequencer_iram.sv``: the same module with its array cut to
2 rows (address bit 0), so ``sequencer``'s DC area is its logic without a
4,096 x 128 flop array (FreePDK45 has no memory macro; asic_memories s.1.1).
The read register and the write path stay. usage: gen_iram_dc.py <minitpu> <out.sv>"""
import sys

src = open(f"{sys.argv[1]}/src/core/sequencer/sequencer_iram.sv").read()
for a, b in (("mem[0:(1 << ADDR_WIDTH)-1]", "mem[0:1]"), ("mem[iram_addr]", "mem[iram_addr[0]]"),
             ("mem[iram_b_addr]", "mem[iram_b_addr[0]]")):
    assert src.count(a) == 1, a
    src = src.replace(a, b)
open(sys.argv[2], "w").write("// generated by gen_iram_dc.py: sequencer_iram at 2 rows (DC stand-in)\n" + src)
