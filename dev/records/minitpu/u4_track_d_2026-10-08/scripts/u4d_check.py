"""U4 track D: ``check.py``'s trace check with the Catapult RTL as the backend.

    $ALLO_PYTHON u4d_check.py <unit> <variant> <prj> [--inst I] [--n N] [--top top]

The unit's own ``VARIANTS[variant]`` runner is called with a stand-in for the
built module (``CatapultRtl``): called with the region's arrays in declaration
order, it drives the Catapult RTL (``<prj>/build/Catapult/<top>.v1/
concat_sim_rtl.v``) in Verilator -- every input port offers row ``t`` until it
is accepted, every output is always ready -- and writes each output port's
tokens back into the caller's array. So the inputs, the output mapping and the
comparison are exactly ``check.check_trace``'s (the RTL oracle, ``u.REF``'s
masks, every defined slot), and only the backend differs. Generalises
``u3_track_c_2026-10-04/scripts/u3c_cmp.py`` (which hard-coded each unit's
port order) to any variant whose runner calls ``mod(*arrays)``.

What the RTL adds over csim is time. Every accepted row and every output token
is stamped with its clock cycle:

* ``L`` per output: the output token's edge minus its row's accept edge (the
  last input port's), ``rtl.py``'s count -- the manifest's number (D-10);
* the rate: cycles per row, and the rows not accepted one cycle after the
  previous one (stall cycles);
* **cycle-for-cycle**: output token ``t`` of every row-aligned output leaves at
  cycle ``t + c`` for one constant ``c`` over the whole trace. With the row's
  values equal to the oracle's row ``t`` that is MiniTPU's timing shifted by
  ``c`` edges -- the per-cycle verdict P-2 asks of Catapult RTL (U3's
  "cycle-equal" is the same with ``c`` = the first row's accept + 1).

Prints the ``UNIT-MATCH``/``UNIT-DIFF`` line (``cycle=per-cycle``) and, when
``<prj>/latency.json`` exists, one ``LATENCY-*`` line per kernel (a lone
kernel: ``latency.verdict`` against the measured ``L``; several: the rate
against the slowest II, ``latency.composite``).
"""
import argparse
import hashlib
import importlib
import inspect
import os
import re
import subprocess
import sys
import time

import numpy as np

sys.path.insert(0, os.getcwd())
from examples.minitpu.harness import check, latency, rtl  # noqa: E402

nw = rtl.nwords


def _w(t):
    m = re.match(r"(?:ac_int|ap_uint|ap_int)<(\d+)", t)
    if m:
        return int(m.group(1))
    return {"bool": 1}[t]


class CatapultRtl:
    """The Catapult RTL of one project, callable as the built module."""

    def __init__(self, prj, top=None):
        if top is None:  # the synthesized top: run.tcl's DESIGN_HIERARCHY (a compose region's name)
            top = re.search(r"-DESIGN_HIERARCHY (\w+)", open(os.path.join(prj, "run.tcl")).read()).group(1)
        self.prj, self.top = prj, top
        k = open(os.path.join(prj, "kernel.cpp")).read()
        blk = k[k.index(f"SC_MODULE({top})"):]
        blk = blk[: blk.index("\n};")]
        if "AlloMemPins" in blk:
            raise RuntimeError("the top has RAM pins (a non-streamable array): not a per-row port")
        self.ports = [(d, p, _w(t)) for d, t, p in re.findall(r"Connections::(In|Out)< (.+?) > (\w+);", blk)]
        self.src = os.path.abspath(os.path.join(prj, "build", "Catapult", f"{top}.v1", "concat_sim_rtl.v"))
        self.stamps = None

    def driver(self, nin, nout):
        ins = [(p, w) for d, p, w in self.ports if d == "In"]
        outs = [(p, w) for d, p, w in self.ports if d == "Out"]
        ni, no = len(ins), len(outs)
        win = sum(nw(w) for _, w in ins)
        drive, fire, ocap = [], [], []
        for i, (p, w) in enumerate(ins):
            off = sum(nw(w2) for _, w2 in ins[:i])
            drive.append(f"    dut.{p}_vld = k[{i}] < NI[{i}];")
            drive.append(f"    if (k[{i}] < NI[{i}]) setp(dut.{p}_dat, &in[k[{i}] * {win} + {off}]); "
                         f"else setp(dut.{p}_dat, zeros);")
            fire.append(f"    fire[{i}] = dut.{p}_vld && dut.{p}_rdy;")
        for o, (p, w) in enumerate(outs):
            ocap.append(f"""    if (dut.{p}_vld && dut.{p}_rdy) {{
      if (j[{o}] < NO[{o}]) {{ getp(dut.{p}_dat, &out{o}[j[{o}] * {nw(w) + 1}]); out{o}[j[{o}] * {nw(w) + 1} + {nw(w)}] = cyc; }}
      ++j[{o}]; last = cyc;
    }}""")
        decl = "\n".join(f"  std::vector<uint64_t> out{o}(NO[{o}] * {nw(w) + 1}, 0);" for o, (p, w) in enumerate(outs))
        wr = "\n".join(f"  std::fwrite(out{o}.data(), 8, out{o}.size(), fo);" for o in range(no))
        done = " && ".join(f"j[{o}] >= NO[{o}]" for o in range(no)) or "true"
        rdy = "\n".join(f"    dut.{p}_rdy = 1;" for p, _ in outs)
        nl = "\n"
        top = self.top
        return f"""// generated by u4d_check.py: multi-port Connections driver, every row and token stamped
#include "V{top}.h"
#include "verilated.h"
#include <cstdint>
#include <cstdio>
#include <vector>
{rtl._TRACE_HELPERS}
static const uint64_t NI[{max(ni, 1)}] = {{{", ".join(str(x) for x in nin) or "0"}}};
static const uint64_t NO[{max(no, 1)}] = {{{", ".join(str(x) for x in nout) or "0"}}};
int main(int argc, char** argv) {{
  Verilated::commandArgs(argc, argv);
  FILE* fi = std::fopen(argv[1], "rb");
  uint64_t n = 0;
  for (int i = 0; i < {ni}; ++i) if (NI[i] > n) n = NI[i];
  std::vector<uint64_t> in(n * {win}), acc(n, 0), accmin(n, ~0ull);
  static const uint64_t zeros[64] = {{0}};
{decl}
  if (std::fread(in.data(), 8, n * {win}, fi) != n * {win}) return 2;
  std::fclose(fi);
  V{top} dut;
  uint64_t k[{max(ni, 1)}] = {{0}}, j[{max(no, 1)}] = {{0}};
  bool fire[{max(ni, 1)}];
  for (int i = 0; i < {ni}; ++i) k[i] = NI[i];
  dut.rst = 0;
{nl.join(drive)}
  for (int r = 0; r < 4; ++r) {{ dut.clk = 0; dut.eval(); dut.clk = 1; dut.eval(); }}
  dut.rst = 1;
  for (int i = 0; i < {ni}; ++i) k[i] = 0;
  uint64_t cyc = 0, last = 0;
  while (!({done})) {{
    dut.clk = 0;
{nl.join(drive)}
{rdy}
    dut.eval();
{nl.join(fire)}
{nl.join(ocap)}
    dut.clk = 1;
    dut.eval();
    for (int i = 0; i < {ni}; ++i)
      if (fire[i]) {{
        if (k[i] < n) {{ if (acc[k[i]] < cyc) acc[k[i]] = cyc; if (accmin[k[i]] > cyc) accmin[k[i]] = cyc; }}
        ++k[i]; last = cyc;
      }}
    ++cyc;
    if (cyc - last > 20000) {{
      std::fprintf(stderr, "stalled at cycle %llu: inputs", (unsigned long long)cyc);
      for (int i = 0; i < {ni}; ++i) std::fprintf(stderr, " %llu", (unsigned long long)k[i]);
      std::fprintf(stderr, "; outputs");
      for (int o = 0; o < {no}; ++o) std::fprintf(stderr, " %llu", (unsigned long long)j[o]);
      std::fprintf(stderr, "\\n");
      return 4;
    }}
  }}
  std::printf("STREAM cycles=%llu n=%llu\\n", (unsigned long long)cyc, (unsigned long long)n);
  FILE* fo = std::fopen(argv[2], "wb");
  std::fwrite(acc.data(), 8, n, fo);
  std::fwrite(accmin.data(), 8, n, fo);
{wr}
  std::fclose(fo);
  return 0;
}}
"""

    def build(self, nin, nout):
        cache = os.environ.get("MINITPU_HARNESS_CACHE", "/work/shared/users/phd/sk3463/scratch/u4d/hcache")
        code = self.driver(nin, nout)
        h = hashlib.sha256(code.encode() + open(self.src, "rb").read()).hexdigest()[:16]
        d = os.path.join(cache, f"cat-{self.top}-{h}")
        exe = os.path.join(d, f"V{self.top}")
        if os.path.exists(exe):
            return exe
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "driver.cpp"), "w").write(code)
        t0 = time.time()
        cmd = ["verilator", "--cc", "--exe", "--build", "-Wno-fatal", "-O3", "--top-module", self.top, "--Mdir", d,
               "-j", "8", self.src, os.path.join(d, "driver.cpp"), "-CFLAGS", "-std=c++17 -O2"]
        r = subprocess.run(cmd, env=dict(os.environ, CXX=rtl._cxx()), capture_output=True, text=True)
        if r.returncode != 0 or not os.path.exists(exe):
            raise RuntimeError(f"verilator build failed:\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
        print(f"VERILATOR built {exe} in {time.time() - t0:.0f}s", flush=True)
        return exe

    def __call__(self, *arrays):
        if len(arrays) != len(self.ports):
            raise RuntimeError(f"{len(arrays)} arrays for {len(self.ports)} top ports")
        ins = [(a, w) for a, (d, p, w) in zip(arrays, self.ports) if d == "In"]
        outs = [(a, w) for a, (d, p, w) in zip(arrays, self.ports) if d == "Out"]
        nin = [len(a) for a, _ in ins]
        nout = [len(a) for a, _ in outs]
        n = max(nin)
        cols = []
        for a, w in ins:
            v = rtl.pack(_rows(a), w)
            if len(v) < n:
                v = np.concatenate([v, np.zeros((n - len(v), v.shape[1]), dtype=np.uint64)])
            cols.append(v)
        stim = np.ascontiguousarray(np.concatenate(cols, axis=1), dtype=np.uint64)
        exe = self.build(nin, nout)
        d = os.path.dirname(exe)
        fi, fo = os.path.join(d, f"in.{os.getpid()}"), os.path.join(d, f"out.{os.getpid()}")
        stim.tofile(fi)
        try:
            r = subprocess.run([exe, fi, fo], capture_output=True, text=True)
            if r.returncode != 0:
                raise RuntimeError(f"driver exited {r.returncode}: {r.stderr[-1500:]}")
            raw = np.fromfile(fo, dtype=np.uint64)
        finally:
            for p in (fi, fo):
                if os.path.exists(p):
                    os.remove(p)
        acc, accmin, off = raw[:n].astype(np.int64), raw[n: 2 * n].astype(np.int64), 2 * n
        out_cyc = []
        names = [p for d_, p, w in self.ports if d_ == "Out"]
        for (a, w), m in zip(outs, nout):
            blk = raw[off: off + m * (nw(w) + 1)].reshape(m, nw(w) + 1)
            off += m * (nw(w) + 1)
            vals = rtl.unpack(blk[:, : nw(w)])
            mask = (1 << w) - 1
            dt = np.asarray(a).dtype
            lanes = a.shape[1] if a.ndim == 2 else 0
            lw = dt.itemsize * 8
            for i, v in enumerate(vals):
                v &= mask
                if lanes:  # a [n, k] lane array: one packed port, lane 0 the LSBs
                    for k_ in range(lanes):
                        a[i, k_] = (v >> (lw * k_)) & ((1 << lw) - 1)
                    continue
                if dt.kind == "i" and v >> (dt.itemsize * 8 - 1):
                    v -= 1 << (dt.itemsize * 8)
                a[i] = v
            out_cyc.append(blk[:, nw(w)].astype(np.int64))
        self.stamps = {"acc": acc, "accmin": accmin, "out": dict(zip(names, out_cyc)), "n": n,
                       "cycles": int(re.search(r"cycles=(\d+)", r.stdout).group(1)),
                       "in_names": [p for d_, p, w in self.ports if d_ == "In"]}


def _rows(a):
    """One Python int per row: a ``[n, k]`` lane array packed lane 0 = LSBs
    (the track-D forms' one wide port per row, U3 track C's C1 form)."""
    a = np.asarray(a)
    if a.ndim == 2:
        lw = a.dtype.itemsize * 8
        m = (1 << lw) - 1
        return [sum((int(x) & m) << (lw * k) for k, x in enumerate(row)) for row in a]
    return [int(x) for x in a.tolist()]  # rtl.pack masks to the port's width


def hist(x):
    v, c = np.unique(np.asarray(x), return_counts=True)
    return dict(zip(v.tolist(), c.tolist()))


def _compact(h):
    """A histogram, or its range when it has many values."""
    if len(h) <= 6:
        return str(h)
    ks = sorted(h)
    return f"{{{len(ks)} values {ks[0]}..{ks[-1]}, {sum(h.values())} tokens}}"


def timing(st, token_ports=()):
    """Rate, per-output L and the cycle-for-cycle test from the stamps.

    ``token_ports``: outputs whose k-th token is not row k (a receiver of a
    Stream that carries one token per valid command): reported, not held to a
    row. Rate = row accepts: (last accept - first accept + 1) / rows."""
    acc, n = st["acc"], st["n"]
    d = np.diff(acc)
    stall = int((acc[-1] - acc[0]) - (n - 1)) if n > 1 else 0
    lines, offs, Ls = [], set(), {}
    for p, cyc in st["out"].items():
        if len(cyc) == n and p not in token_ports:
            L = hist(cyc - acc)
            off = hist(cyc - np.arange(n))
            Ls[p] = L
            offs |= set(off)
            lines.append((p, L, off))
        else:
            lines.append((p, None, None))
    c4c = len(offs) == 1 and stall == 0
    return {"rate": (acc[-1] - acc[0] + 1) / n, "cycles": st["cycles"], "first_acc": int(acc[0]),
            "stall_cycles": stall, "intervals_1": int((d == 1).sum()), "rows": n, "L": Ls, "lines": lines,
            "offset": sorted(offs), "c4c": c4c}


def check_vectors(u, a):
    """A ``comb``/``valid`` unit (``check.main``'s path): the unit's stimulus
    through the RTL oracle, the variant's runner on the Catapult RTL; per
    vector, with the same timing report (one row per vector)."""
    name = os.path.basename(a.prj.rstrip("/")).replace(".prj", "")
    stim = u.stimulus() if hasattr(u, "stimulus") else None
    if a.n:
        stim = stim[: a.n]
    n = len(stim)
    want, _ = rtl.run(u.RTL, stim.astype(np.uint64))
    want = want[:, 0]
    make, runner = u.VARIANTS[a.variant]
    mod = CatapultRtl(a.prj, a.top)
    t = time.time()
    got = np.asarray(runner(mod, stim)).astype(np.uint64)
    k = int((got != want.astype(np.uint64)).sum())
    outs_ = [p for d_, p, w_ in mod.ports if d_ == "Out"]
    tm = timing(mod.stamps)
    tag = "UNIT-MATCH" if k == 0 else "UNIT-DIFF "
    allL = {}
    for nm, L, off in tm["lines"]:
        for x, c in (L or {}).items():
            allL[x] = allL.get(x, 0) + c
    print(f"{tag} {a.unit} {a.variant} catapult-rtl[{name}] {n - k}/{n} vs MiniTPU RTL cycle=per-vector: "
          f"{tm['rate']:.4f} cyc/vector, stall cycles {tm['stall_cycles']}, L {_compact(allL)} "
          f"(declared {u.RTL.latency}); CYCLE-FOR-CYCLE {'yes' if tm['c4c'] and k == 0 else 'no'} "
          f"(run {time.time() - t:.1f}s)", flush=True)
    mpath = os.path.join(a.prj, "latency.json")
    if os.path.exists(mpath):
        man = latency.load(a.prj)
        ks_ = sorted(man.get("units", {}))
        print("    " + latency.verdict(man, ks_[0], allL or {0: 1}, tm["rate"], a.declared))
    return 1 if k else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("unit"); ap.add_argument("variant"); ap.add_argument("prj")
    ap.add_argument("--inst", default=None)
    ap.add_argument("--n", type=int, default=0)
    ap.add_argument("--top", default=None)
    ap.add_argument("--declared", type=int, default=None, help="the unit's pinned I/O latency (default: none)")
    ap.add_argument("--token-outs", type=int, nargs="*", default=[],
                    help="indices (0-based, among the top's Out ports) of outputs that carry tokens, not rows")
    ap.add_argument("--shift", type=int, default=0,
                    help="rows of delay before the outputs (Wire-linked composites): got[t] held to rtl[t - shift]")
    a = ap.parse_args()
    u = importlib.import_module(f"examples.minitpu.units.{a.unit}")
    if u.RTL.shape != "trace":
        return check_vectors(u, a)
    inst = a.inst or u.DEFAULT
    unit = u.INSTANCES[inst]
    w = u.WIDTH[inst]
    name = os.path.basename(a.prj.rstrip("/")).replace(".prj", "")
    t0 = time.time()
    cmd, spans = check._trace_all(u, inst, a.n, None if a.variant.startswith("form:") else a.variant)
    n = len(next(iter(cmd.values())))
    packed = {p: rtl.pack(cmd[p], wd) for p, wd in unit.inputs}
    rtl_out = rtl.run_trace(unit, packed, seed=1)
    want, reason, _ = u.REF(inst, packed)
    ndef = sum(int((reason[p] == "").sum()) for p in want)
    bad_ref = sum(int(((reason[p] == "") & (rtl_out[p] != want[p]).any(axis=1)).sum()) for p in want)
    print(f"RTL {unit.top}:{inst}: {n} cycles in {len(spans)} traces, {ndef} defined slots, "
          f"RTL vs reference on defined: {ndef - bad_ref}/{ndef} ({time.time() - t0:.1f}s)", flush=True)
    rtl_int = {p: rtl.unpack(rtl_out[p]) for p in want}
    if a.variant.startswith("form:"):  # a track-D form: ../forms/<name>.py, ``make`` and ``run``
        sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "forms"))
        runner = importlib.import_module(a.variant[5:]).run
    else:
        make, runner = u.VARIANTS[a.variant]
    shift = getattr(u, "RESP_SHIFT", {}).get(a.variant)
    shift = shift(inst) if callable(shift) else (shift or {})
    mod = CatapultRtl(a.prj, a.top)
    t = time.time()
    try:
        got = runner(mod, cmd, n, w)
    except Exception as e:  # noqa: BLE001
        print(f"UNIT-FAIL  {a.unit}:{inst} {a.variant} catapult-rtl {name}: {type(e).__name__}: {str(e)[:1500]}")
        return 1
    k = tot = masked = masked_eq = 0
    per_label, first, census = {}, [], {}
    for p in want:
        g = [int(x) for x in got[p]]
        r = rtl_int[p]
        ks = shift.get(p, 0) - a.shift
        for i in range(max(0, ks), n + min(0, ks)):
            why = reason[p][i]
            if why:
                masked += 1
                census[why] = census.get(why, 0) + 1
                masked_eq += int(g[i - ks] == r[i])
                continue
            tot += 1
            if g[i - ks] != r[i]:
                k += 1
                lab = next(lb for lb, s0, s1 in spans if s0 <= i < s1)
                per_label[lab] = per_label.get(lab, 0) + 1
                if len(first) < 4:
                    first.append(f"{lab} cycle {i} {p}: catapult {g[i - ks]:x} rtl {r[i]:x}")
    outs_ = [p for d_, p, w_ in mod.ports if d_ == "Out"]
    tm = timing(mod.stamps, {outs_[i] for i in a.token_outs})
    tag = "UNIT-MATCH" if k == 0 else "UNIT-DIFF "
    cen = ", ".join(f"{x}={y}" for x, y in sorted(census.items()))
    print(f"{tag} {a.unit}:{inst} {a.variant} catapult-rtl[{name}] {tot - k}/{tot} defined ({masked} masked: {cen}; "
          f"catapult==rtl on {masked_eq}) cycle=per-cycle: {tm['rate']:.4f} cyc/row ({tm['cycles']} cycles in all), stall cycles "
          f"{tm['stall_cycles']}, row->token offset {tm['offset'][:6]}; CYCLE-FOR-CYCLE "
          f"{'yes' if tm['c4c'] and k == 0 else 'no'} (run {time.time() - t:.1f}s)", flush=True)
    if k:
        print("    differing defined slots by trace: " + ", ".join(f"{lb}={c}" for lb, c in per_label.items()))
        for f in first:
            print(f"    e.g. {f}")
    allL = {}
    for nm, L, off in tm["lines"]:
        if L is None:
            c = mod.stamps["out"][nm]
            print(f"    port {nm}: {len(c)} tokens (not held to rows), cycles {int(c.min()) if len(c) else '-'}.."
                  f"{int(c.max()) if len(c) else '-'}")
            continue
        for x, c in L.items():
            allL[x] = allL.get(x, 0) + c
    print(f"    L (accept edge -> token edge) over every row-aligned output: {_compact(allL)}; "
          f"first row accepted at cycle {tm['first_acc']}; rows at interval 1: {tm['intervals_1']}/{tm['rows'] - 1}")
    per = {}
    for nm, L, off in tm["lines"]:
        if L is not None:
            per.setdefault(_compact(L), []).append(nm)
    for L, nms in per.items():
        print(f"    L {L}: {', '.join(nms)}")
    mpath = os.path.join(a.prj, "latency.json")
    if os.path.exists(mpath):
        man = latency.load(a.prj)
        ks_ = sorted(man.get("units", {}))
        if len(ks_) == 1:
            print("    " + latency.verdict(man, ks_[0], allL or {0: 1}, tm["rate"], a.declared))
        else:
            print("    " + latency.composite(man, ks_, allL or {0: 1}, tm["rate"]))
            for kk in ks_:
                uu = man["units"][kk]
                print(f"      {kk}: latency {uu.get('latency')} ii {uu.get('ii')} ({uu.get('status')}"
                      f"{': ' + uu.get('reason', '') if uu.get('status') != 'scheduled' else ''})")
    small = {}
    for p_, v_ in got.items():
        try:
            small[f"got_{p_}"] = np.asarray([int(x) for x in v_], dtype=np.uint64)
        except (OverflowError, TypeError, ValueError):
            pass
    np.savez_compressed(os.path.join(a.prj, "u4d_stamps.npz"), acc=mod.stamps["acc"],
                        outs=np.asarray(outs_), **{f"out_{p}": c for p, c in mod.stamps["out"].items()}, **small)
    return 1 if k else 0


if __name__ == "__main__":
    sys.exit(main())
