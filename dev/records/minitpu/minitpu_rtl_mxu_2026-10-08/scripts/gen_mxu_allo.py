"""Write ``mxu_allo.sv``: MiniTPU's ``mxu`` module (``src/core/mxu/mxu.sv``'s
port list, unchanged) around the Catapult RTL of the ``mxu_wide`` form.

    python3 gen_mxu_allo.py <prj> <out.sv> [--fifo-depth 1024]

The region's ten Connections ports are read from ``<prj>/kernel.cpp`` in
region-argument order (rst, push, kind, data, cmt, pop | rdy, acc, vld,
odata). The core runs in TOKEN time (one iteration of every kernel per token,
the token index is ``mxu.sv``'s cycle); the wrapper is the adapter from
MiniTPU's cycle time:

* every In port gets one token per clock, through a wrapper FIFO so that a
  stall of the core (back-pressure inside the grid) delays tokens rather than
  losing them; a FIFO that fills is a *lockstep violation* (the core's
  throughput is below one token per cycle) and is flagged, not hidden;
* every Out port is always ready; the latest ``rdy``/``acc``/``vld``/``odata``
  tokens are registered and shown;
* the output side lags the input side by the grid's pipeline depth, so a pop
  MiniTPU issues at cycle ``c`` (token ``c``) is reflected in the ``vld`` token
  ``c`` which arrives ``lag`` cycles later: until then ``output_valid_o`` is
  masked (``out_tokens > last_pop_token``), or MiniTPU would pop a stale
  head. That mask is what makes ``issue_interval.vmatpop`` a version delta.
* ``lag_o`` (an extra, non-contract output) is ``in_tokens - out_tokens``,
  the measured token lag, so a testbench can report it.

Reset: MiniTPU's ``rst_ni`` drives the core's async active-low ``rst`` AND
the ``rst`` token (``mxu_unit``'s D-14 control clear).
"""
import argparse, os, re

ap = argparse.ArgumentParser()
ap.add_argument("prj"); ap.add_argument("out")
ap.add_argument("--fifo-depth", type=int, default=1024)
a = ap.parse_args()
k = open(os.path.join(a.prj, "kernel.cpp")).read()
mods = re.findall(r"^SC_MODULE\((\w+)\)", k, re.M)
TOP = mods[mods.index("tb") - 1]
blk = k[k.index(f"SC_MODULE({TOP})"):]
blk = blk[: blk.index("\n};")]
ins = re.findall(r"Connections::In< (.+?) > (\w+);", blk)
outs = re.findall(r"Connections::Out< (.+?) > (\w+);", blk)
assert len(ins) == 6 and len(outs) == 4, (ins, outs)


def w(t):
    m = re.match(r"(?:ac_int|ap_uint|ap_int)<(\d+)", t)
    return int(m.group(1)) if m else {"bool": 1}[t]


(p_rst, p_push, p_kind, p_data, p_cmt, p_pop) = [p for _, p in ins]
(p_rdy, p_acc, p_vld, p_od) = [p for _, p in outs]
DW = w(ins[3][0]); OW = w(outs[3][0])
D = DW // 16
SUB = OW // (16 * D)
m = re.search(r"mxu_wide_(dim\d+)", TOP)
print(f"top {TOP}: D={D} SUB={SUB} data {DW}b odata {OW}b; in {[p for _, p in ins]} out {[p for _, p in outs]}")

sv = f"""// GENERATED by gen_mxu_allo.py from {a.prj}/kernel.cpp -- do not edit.
// MiniTPU's `mxu` port list (src/core/mxu/mxu.sv) around the Allo/Catapult RTL `{TOP}`
// (examples/minitpu/units/mxu_unit.py as the packed-port form mxu_wide.py), see the docstring of gen_mxu_allo.py.
`timescale 1ns/1ps

module mrtl_tokfifo #(parameter int unsigned W = 1, parameter int unsigned DEPTH = {a.fifo_depth}) (
  input  logic clk_i, input logic rst_ni,
  input  logic push_i, input logic [W-1:0] data_i,
  input  logic pop_i, output logic [W-1:0] data_o, output logic empty_o, output logic full_o,
  output logic [31:0] pushed_o, output logic [31:0] popped_o);
  logic [W-1:0] mem [DEPTH];
  logic [$clog2(DEPTH):0] wr_q, rd_q;
  assign empty_o = wr_q == rd_q;
  assign full_o = (wr_q[$clog2(DEPTH)] != rd_q[$clog2(DEPTH)]) && (wr_q[$clog2(DEPTH)-1:0] == rd_q[$clog2(DEPTH)-1:0]);
  assign data_o = mem[rd_q[$clog2(DEPTH)-1:0]];
  always_ff @(posedge clk_i or negedge rst_ni) begin
    if (!rst_ni) begin
      wr_q <= '0; rd_q <= '0; pushed_o <= 0; popped_o <= 0;
    end else begin
      if (push_i && !full_o) begin mem[wr_q[$clog2(DEPTH)-1:0]] <= data_i; wr_q <= wr_q + 1'b1; pushed_o <= pushed_o + 1; end
      if (pop_i && !empty_o) begin rd_q <= rd_q + 1'b1; popped_o <= popped_o + 1; end
    end
  end
endmodule

module mxu #(
  parameter int unsigned DIM = vpu_pkg::NUM_LANES,
  parameter int unsigned FIFO_DEPTH = vpu_pkg::MXU_FIFO_DEPTH,
  parameter int unsigned OUTPUT_FIFO_DEPTH = vpu_pkg::MXU_OUTPUT_FIFO_DEPTH
) (
  input  logic clk_i,
  input  logic rst_ni,
  input  logic                              input_push_i,
  input  vpu_pkg::mxu_input_kind_e      input_kind_i,
  input  logic [DIM-1:0][vpu_pkg::DATA_WIDTH-1:0] input_data_i,
  output logic                              input_ready_o,
  output logic                              input_accept_o,
  input  logic                              weight_commit_i,
  input  logic                              output_pop_i,
  output logic                              output_valid_o,
  output logic [vpu_pkg::NUM_SUBLANES-1:0][DIM-1:0][vpu_pkg::DATA_WIDTH-1:0] output_data_o
);
  import vpu_pkg::*;
  localparam int unsigned ALLO_DIM = {D};
  localparam int unsigned ALLO_SUB = {SUB};
  if (DIM != ALLO_DIM) begin : g_chk_dim
    $error("mxu_allo: the Allo core was built at DIM %0d, instantiated at DIM %0d", ALLO_DIM, DIM);
  end
  if (NUM_SUBLANES != ALLO_SUB) begin : g_chk_sub
    $error("mxu_allo: the Allo core was built at NUM_SUBLANES %0d, instantiated at %0d", ALLO_SUB, NUM_SUBLANES);
  end
  if (OUTPUT_FIFO_DEPTH != 64) begin : g_chk_ofifo
    $error("mxu_allo: the Allo core's lane rings hold 64 rows (ENTRIES 16 x 4); OUTPUT_FIFO_DEPTH %0d", OUTPUT_FIFO_DEPTH);
  end

  // ---- input tokens: one per clock, FIFO'd into the core ----
  logic [{DW}-1:0] data_flat;
  always_comb for (int unsigned c = 0; c < ALLO_DIM; c++) data_flat[16*c +: 16] = input_data_i[c];
  logic kind_bit;
  assign kind_bit = (input_kind_i == MXU_INPUT_RHS);

  logic f_rst_d, f_push_d, f_kind_d, f_cmt_d, f_pop_d;
  logic [{DW}-1:0] f_data_d;
  logic f_rst_e, f_push_e, f_kind_e, f_data_e, f_cmt_e, f_pop_e;
  logic f_rst_f, f_push_f, f_kind_f, f_data_f, f_cmt_f, f_pop_f;
  logic [31:0] n_rst_in, n_push_in, n_kind_in, n_data_in, n_cmt_in, n_pop_in;
  logic [31:0] n_rst_out, n_push_out, n_kind_out, n_data_out, n_cmt_out, n_pop_out;
  logic c_rst_vld, c_push_vld, c_kind_vld, c_data_vld, c_cmt_vld, c_pop_vld;
  logic c_rst_rdy, c_push_rdy, c_kind_rdy, c_data_rdy, c_cmt_rdy, c_pop_rdy;
  logic c_rdy_vld, c_acc_vld, c_vld_vld, c_od_vld;
  logic c_rdy_dat, c_acc_dat, c_vld_dat;
  logic [{OW}-1:0] c_od_dat;
  logic core_done;

  mrtl_tokfifo #(.W(1)) f_rst (.clk_i, .rst_ni, .push_i(1'b1), .data_i(rst_ni), .pop_i(c_rst_vld && c_rst_rdy), .data_o(f_rst_d), .empty_o(f_rst_e), .full_o(f_rst_f), .pushed_o(n_rst_in), .popped_o(n_rst_out));
  mrtl_tokfifo #(.W(1)) f_push (.clk_i, .rst_ni, .push_i(1'b1), .data_i(input_push_i), .pop_i(c_push_vld && c_push_rdy), .data_o(f_push_d), .empty_o(f_push_e), .full_o(f_push_f), .pushed_o(n_push_in), .popped_o(n_push_out));
  mrtl_tokfifo #(.W(1)) f_kind (.clk_i, .rst_ni, .push_i(1'b1), .data_i(kind_bit), .pop_i(c_kind_vld && c_kind_rdy), .data_o(f_kind_d), .empty_o(f_kind_e), .full_o(f_kind_f), .pushed_o(n_kind_in), .popped_o(n_kind_out));
  mrtl_tokfifo #(.W({DW})) f_data (.clk_i, .rst_ni, .push_i(1'b1), .data_i(data_flat), .pop_i(c_data_vld && c_data_rdy), .data_o(f_data_d), .empty_o(f_data_e), .full_o(f_data_f), .pushed_o(n_data_in), .popped_o(n_data_out));
  mrtl_tokfifo #(.W(1)) f_cmt (.clk_i, .rst_ni, .push_i(1'b1), .data_i(weight_commit_i), .pop_i(c_cmt_vld && c_cmt_rdy), .data_o(f_cmt_d), .empty_o(f_cmt_e), .full_o(f_cmt_f), .pushed_o(n_cmt_in), .popped_o(n_cmt_out));
  mrtl_tokfifo #(.W(1)) f_pop (.clk_i, .rst_ni, .push_i(1'b1), .data_i(output_pop_i), .pop_i(c_pop_vld && c_pop_rdy), .data_o(f_pop_d), .empty_o(f_pop_e), .full_o(f_pop_f), .pushed_o(n_pop_in), .popped_o(n_pop_out));
  assign c_rst_vld = !f_rst_e; assign c_push_vld = !f_push_e; assign c_kind_vld = !f_kind_e;
  assign c_data_vld = !f_data_e; assign c_cmt_vld = !f_cmt_e; assign c_pop_vld = !f_pop_e;

  // a wrapper FIFO filling = the core consumed fewer tokens than cycles elapsed: lockstep violation
  logic lockstep_violation_q;
  always_ff @(posedge clk_i or negedge rst_ni)
    if (!rst_ni) lockstep_violation_q <= 1'b0;
    else if (f_rst_f || f_push_f || f_kind_f || f_data_f || f_cmt_f || f_pop_f) lockstep_violation_q <= 1'b1;

  {TOP} i_core (
    .clk(clk_i), .rst(rst_ni), .done(core_done),
    .{p_rst}_dat(f_rst_d), .{p_rst}_vld(c_rst_vld), .{p_rst}_rdy(c_rst_rdy),
    .{p_push}_dat(f_push_d), .{p_push}_vld(c_push_vld), .{p_push}_rdy(c_push_rdy),
    .{p_kind}_dat(f_kind_d), .{p_kind}_vld(c_kind_vld), .{p_kind}_rdy(c_kind_rdy),
    .{p_data}_dat(f_data_d), .{p_data}_vld(c_data_vld), .{p_data}_rdy(c_data_rdy),
    .{p_cmt}_dat(f_cmt_d), .{p_cmt}_vld(c_cmt_vld), .{p_cmt}_rdy(c_cmt_rdy),
    .{p_pop}_dat(f_pop_d), .{p_pop}_vld(c_pop_vld), .{p_pop}_rdy(c_pop_rdy),
    .{p_rdy}_dat(c_rdy_dat), .{p_rdy}_vld(c_rdy_vld), .{p_rdy}_rdy(1'b1),
    .{p_acc}_dat(c_acc_dat), .{p_acc}_vld(c_acc_vld), .{p_acc}_rdy(1'b1),
    .{p_vld}_dat(c_vld_dat), .{p_vld}_vld(c_vld_vld), .{p_vld}_rdy(1'b1),
    .{p_od}_dat(c_od_dat), .{p_od}_vld(c_od_vld), .{p_od}_rdy(1'b1)
  );

  // ---- output tokens: latest shown; token counters ----
  logic rdy_q, acc_q, vld_q;
  logic [{OW}-1:0] od_q;
  logic [31:0] n_vld_out, n_od_out, n_acc_out;
  logic [31:0] last_pop_token_q;   // the pop token index (= cycle) of the last pop MiniTPU issued while valid
  always_ff @(posedge clk_i or negedge rst_ni) begin
    if (!rst_ni) begin
      rdy_q <= 1'b1; acc_q <= 1'b0; vld_q <= 1'b0; od_q <= '0; n_vld_out <= 0; n_od_out <= 0; n_acc_out <= 0;
      last_pop_token_q <= 0;
    end else begin
      if (c_rdy_vld) rdy_q <= c_rdy_dat;
      if (c_acc_vld) begin acc_q <= c_acc_dat; n_acc_out <= n_acc_out + 1; end
      if (c_vld_vld) begin vld_q <= c_vld_dat; n_vld_out <= n_vld_out + 1; end
      if (c_od_vld) begin od_q <= c_od_dat; n_od_out <= n_od_out + 1; end
      // this cycle's pop is token n_pop_in (the FIFO's push count before the edge); its effect is in vld token n_pop_in + 1
      if (output_pop_i && output_valid_o) last_pop_token_q <= n_pop_in + 1;
    end
  end
  assign input_ready_o = rdy_q;
  assign input_accept_o = acc_q;
  // valid only once the vld token that already reflects the last pop has arrived (tokens received > its index)
  assign output_valid_o = vld_q && (n_vld_out > last_pop_token_q);
  always_comb
    for (int unsigned s = 0; s < ALLO_SUB; s++)
      for (int unsigned c = 0; c < ALLO_DIM; c++)
        output_data_o[s][c] = od_q[16*(s*ALLO_DIM + c) +: 16];

  // ---- probes (not contract ports): token lag and lockstep health ----
  logic [31:0] lag_o, acc_lag_o;
  assign lag_o = n_push_in - n_vld_out;       // output side: vld tokens behind the input tokens
  assign acc_lag_o = n_push_in - n_acc_out;   // input side: acc tokens behind the input tokens
  logic lockstep_violation_o;
  assign lockstep_violation_o = lockstep_violation_q;
`ifndef SYNTHESIS
  always_ff @(posedge clk_i)
    if (rst_ni && (f_rst_f || f_push_f || f_kind_f || f_data_f || f_cmt_f || f_pop_f))
      $error("mxu_allo: lockstep violation -- a wrapper token FIFO is full (core throughput < 1 token/cycle)");
`endif
endmodule : mxu
"""
open(a.out, "w").write(sv)
print(f"wrote {a.out}")
