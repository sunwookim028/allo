def system_message(disposition: str) -> str:
    """The system prompt. The workload is substituted by `task()`."""
    return {"using": USING, "maintaining": MAINTAINING}[disposition]


def task(disposition: str, workload: str, angle: str, best: dict | None,
         history: list[str]) -> str:
    """The per-iteration prompt: the brief, the current best, what was tried."""
    spec = workloads.get(workload)
    brief = system_message(disposition).format(
        workload=workloads.brief(spec), common=COMMON)
    tried = ("\n".join(f"  - {h}" for h in history[-8:]) if history
             else "  (nothing tried yet)")
    state = "  (no baseline measured yet)"
    if best:
        state = "\n".join(
            f"  {c}: cycles {json.dumps(v.get('cycles'))} "
            f"area {json.dumps(v.get('area'))} "
            f"est_clock {v.get('estimated_ns')} ns"
            for c, v in sorted((best or {}).items()))
    return f"""{brief}

YOUR ANGLE for this search: {angle}

THE MEASURED BASELINE, per design case:
{state}

Already attempted in this search:
{tried}

Propose ONE candidate. Read before you edit. Build before you claim anything
about C++. Then, in your final message, in this order:

1. THE DIAGNOSIS: which of the four kinds of refusal you think you found, and
   your evidence. If it is (3) or (4), say so and stop -- that is a result.
2. What abstraction you added, and which of the five places a primitive lands
   in you touched.
3. Which design cases it should pay off on, and why. If it helps one and not
   another, say so -- that is a finding, not a failure.
4. The test you WOULD add: which file, which three cases. You cannot write it.
5. Whether it relies on anything the gates happen not to exercise, and whether
   what it expresses is a promise rather than a fact.
"""
